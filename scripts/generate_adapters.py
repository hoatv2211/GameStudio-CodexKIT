def _fsync_directory_best_effort(directory: Path) -> None:
    try:
        descriptor = os.open(directory, os.O_RDONLY)
    except (AttributeError, OSError):
        return
    try:
        try:
            os.fsync(descriptor)
        except OSError:
            pass
    finally:
        os.close(descriptor)

def _recovery_generation_revision(path: Path) -> int | None:
    name = path.name
    if name == "recovery.json":
        return 0
    if not name.startswith("recovery.") or not name.endswith(".json"):
        return None
    generation = name[len("recovery."):-len(".json")]
    if len(generation) != 8 or not generation.isdigit():
        return None
    return int(generation)

def _next_recovery_revision(recovery_path: Path, recovery: dict[str, object]) -> int:
    current = recovery.get("revision", -1)
    if not isinstance(current, int) or isinstance(current, bool) or current < -1:
        raise OSError("quarantine recovery manifest revision is invalid")
    highest = current
    root = recovery_path.parent
    try:
        with os.scandir(root) as entries:
            for entry in entries:
                revision = _recovery_generation_revision(root / entry.name)
                if revision is not None:
                    highest = max(highest, revision)
    except OSError:
        pass
    return highest + 1

def _publish_recovery_payload(
    target: Path,
    payload: str,
    recovery: dict[str, object],
) -> None:
    temporary = target.with_name(f".{target.name}.{uuid.uuid4().hex}.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        if json.loads(temporary.read_text(encoding="utf-8")) != recovery:
            raise OSError("quarantine recovery manifest verification failed")
        temporary.replace(target)
        _fsync_directory_best_effort(target.parent)
        if json.loads(target.read_text(encoding="utf-8")) != recovery:
            raise OSError("quarantine recovery manifest publication verification failed")
    finally:
        if os.path.lexists(temporary):
            try:
                temporary.unlink()
            except OSError:
                pass

def _write_quarantine_recovery_manifest(
    recovery_path: Path,
    recovery: dict[str, object],
) -> Path:
    revision = _next_recovery_revision(recovery_path, recovery)
    recovery["revision"] = revision
    recovery["generation"] = revision
    payload = json.dumps(recovery, indent=2) + "\n"
    canonical = (
        recovery_path.parent / "recovery.json"
        if recovery_path.name == "recovery.json"
        or _recovery_generation_revision(recovery_path) is not None
        else recovery_path
    )
    try:
        _publish_recovery_payload(canonical, payload, recovery)
        return canonical
    except PermissionError:
        if canonical.name != "recovery.json" or not _is_real_regular_file(canonical):
            raise
    generation_path = canonical.parent / f"recovery.{revision:08d}.json"
    if os.path.lexists(generation_path):
        raise OSError("quarantine recovery generation already exists")
    _publish_recovery_payload(generation_path, payload, recovery)
    return generation_path

