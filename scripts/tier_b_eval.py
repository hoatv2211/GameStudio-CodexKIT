from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

try:
    from scripts.common import load_yaml, parse_frontmatter
except ModuleNotFoundError:
    from common import load_yaml, parse_frontmatter


GENERATED_MARKER = "Generated by scripts/tier_b_eval.py. Do not edit manually."


def _skill_descriptions(root: Path) -> list[dict[str, str]]:
    registry = load_yaml(root / "registry" / "capabilities.yaml")
    descriptions: list[dict[str, str]] = []
    for capability in registry.get("capabilities", []):
        skill_path = root / capability["path"]
        if not skill_path.exists():
            continue
        frontmatter, _ = parse_frontmatter(skill_path)
        descriptions.append({"name": capability["id"], "description": frontmatter["description"]})
    return descriptions


def export_cases(root: Path | str, output: Path | str) -> int:
    root_path = Path(root).resolve()
    output_path = Path(output)
    descriptions = _skill_descriptions(root_path)
    rows: list[dict[str, Any]] = []
    for case_file in sorted((root_path / "evals" / "routing").glob("*.json")):
        payload = json.loads(case_file.read_text(encoding="utf-8"))
        for index, case in enumerate(payload.get("cases", []), start=1):
            rows.append(
                {
                    "id": f"{payload['target_skill']}:{index}",
                    "prompt": case["prompt"],
                    "expected_skill": case["expected_skill"],
                    "type": case["type"],
                    "candidate_skills": descriptions,
                    "runner_contract": "Return one selected_skill and a concise rationale. Do not mutate files.",
                }
            )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "".join(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n" for row in rows),
        encoding="utf-8",
    )
    return len(rows)


def write_blocked_status(path: Path | str, reason: str) -> Path:
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "_generated": GENERATED_MARKER,
        "verdict": "BLOCKED",
        "reason": reason,
        "runner": "Hermes",
        "observed_cases": 0,
        "pass_rate": None,
    }
    output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return output


def validate_results(export_path: Path | str, results_path: Path | str) -> dict[str, Any]:
    expected = {
        row["id"]: row
        for row in (
            json.loads(line)
            for line in Path(export_path).read_text(encoding="utf-8").splitlines()
            if line.strip()
        )
    }
    results = json.loads(Path(results_path).read_text(encoding="utf-8"))
    observed = {item["id"]: item for item in results}
    missing = sorted(set(expected) - set(observed))
    mismatches = sorted(
        case_id
        for case_id in set(expected).intersection(observed)
        if observed[case_id].get("selected_skill") != expected[case_id]["expected_skill"]
    )
    passed = len(expected) - len(missing) - len(mismatches)
    return {
        "verdict": "PASS" if not missing and not mismatches else "FAIL",
        "total": len(expected),
        "passed": passed,
        "missing": missing,
        "mismatches": mismatches,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export or validate Hermes-oriented Tier-B routing cases.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--export", type=Path)
    parser.add_argument("--results", type=Path)
    parser.add_argument("--status", type=Path)
    args = parser.parse_args(argv)
    if args.export:
        count = export_cases(Path(args.root), args.export)
        print(f"tier-b-export: {count} cases")
    if args.results:
        if not args.export:
            parser.error("--results requires --export")
        report = validate_results(args.export, args.results)
        print(json.dumps(report, indent=2))
        return 0 if report["verdict"] == "PASS" else 1
    if args.status:
        write_blocked_status(args.status, "No Hermes model runner was invoked by the deterministic local workflow")
        print(args.status)
    return 0


if __name__ == "__main__":
    sys.exit(main())
