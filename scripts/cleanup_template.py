REQUIRED_REVIEWER = "QA Lead"
TOKEN_PREFIX = "APPLY-CLEAN-TEMPLATE-"
BACKUP_CATEGORIES = {"hermes-state", "historical-reports", "dated-evidence"}
GENERATED_MARKER = "Generated by scripts/cleanup_template.py. Do not edit manually."


class CleanupBlocked(RuntimeError):
    pass


def _root(path: Path | str) -> Path:
    root = Path(path).resolve()
    if not root.is_dir():
        raise CleanupBlocked(f"cleanup root is not a directory: {root}")
    return root


def _absolute_inside(root: Path, path: Path) -> Path:
    absolute = Path(os.path.abspath(path))
    try:
        relative = absolute.relative_to(root)
    except ValueError as error:
        raise CleanupBlocked(f"target escapes cleanup root: {path}") from error
    if relative == Path("."):
        raise CleanupBlocked("cleanup target cannot be the repository root")
    return absolute


def _is_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    try:
        attributes = os.lstat(path).st_file_attributes
    except (AttributeError, FileNotFoundError, OSError):
        return False
    return bool(attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)


def _assert_no_reparse(root: Path, path: Path) -> None:
    candidate = _absolute_inside(root, path)
    current = candidate
    while current != root:
        if current.exists() and _is_reparse(current):
            raise CleanupBlocked(f"refusing reparse or symlink target: {current}")
        current = current.parent


def _tree_entries(root: Path, target: Path) -> list[tuple[str, str, Path]]:
    _assert_no_reparse(root, target)
    if not target.exists():
        return []
    if target.is_file():
        return [(target.name, "file", target)]
    entries: list[tuple[str, str, Path]] = []
    stack = [target]
    while stack:
        directory = stack.pop()
        if _is_reparse(directory):
            raise CleanupBlocked(f"refusing reparse or symlink target: {directory}")
        children = sorted(directory.iterdir(), key=lambda item: item.name.casefold(), reverse=True)
        if directory != target and not children:
            entries.append((directory.relative_to(target).as_posix(), "directory", directory))
        for child in children:
            if _is_reparse(child):
                raise CleanupBlocked(f"refusing reparse or symlink target: {child}")
            relative = child.relative_to(target).as_posix()
            if child.is_dir():
                entries.append((relative, "directory", child))
                stack.append(child)
            elif child.is_file():
                entries.append((relative, "file", child))
            else:
                raise CleanupBlocked(f"unsupported filesystem entry: {child}")
    return sorted(entries, key=lambda item: (item[0], item[1]))


def _path_fingerprint(root: Path, target: Path) -> tuple[str, int, int]:
    entries = _tree_entries(root, target)
    hasher = hashlib.sha256()
    total_bytes = 0
    file_count = 0
    if target.is_dir():
        hasher.update(b"root-directory\0")
    for relative, kind, path in entries:
        hasher.update(kind.encode("ascii") + b"\0")
        hasher.update(relative.encode("utf-8") + b"\0")
        if kind == "file":
            file_count += 1
            size = path.stat().st_size
            total_bytes += size
            hasher.update(str(size).encode("ascii") + b"\0")
            with path.open("rb") as stream:
                for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                    hasher.update(chunk)
    return hasher.hexdigest(), total_bytes, file_count


def _covered(path: Path, targets: Iterable[Path]) -> bool:
    return any(path == target or target in path.parents for target in targets)


def _discover_cache_targets(root: Path, existing: list[Path]) -> list[Path]:
    found: list[Path] = []
    for current_text, directories, _files in os.walk(root, topdown=True, followlinks=False):
        current = Path(current_text)
        kept: list[str] = []
        for name in directories:
            candidate = current / name
            if name == ".git" or _covered(candidate, [*existing, *found]):
                continue
            if name == "__pycache__":
                found.append(candidate)
                continue
            kept.append(name)
        directories[:] = kept
    return sorted(found, key=lambda item: item.as_posix())


def _git(repo: Path, *args: str, required: bool = True) -> str:
    safe_directory = f"safe.directory={repo.as_posix()}"
    result = subprocess.run(
        ["git", "-c", safe_directory, "-C", str(repo), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode and required:
        detail = result.stderr.strip() or result.stdout.strip()
        raise CleanupBlocked(f"git {' '.join(args)} failed for {repo}: {detail}")
    return result.stdout.strip() if result.returncode == 0 else ""


def _upstream_sources(root: Path) -> dict[str, dict[str, Any]]:
    path = root / "registry" / "upstream-sources.yaml"
    if not path.exists():
        raise CleanupBlocked("registry/upstream-sources.yaml is required before removing .research")
    payload = load_yaml(path)
    sources = payload.get("sources", []) if isinstance(payload, dict) else []
    result: dict[str, dict[str, Any]] = {}
    for source in sources:
        if not isinstance(source, dict):
            raise CleanupBlocked("upstream source entries must be mappings")
        restore_path = source.get("restore_path")
        if not isinstance(restore_path, str) or not restore_path:
            raise CleanupBlocked("every upstream source requires restore_path")
        if restore_path in result:
            raise CleanupBlocked(f"duplicate upstream restore_path: {restore_path}")
        result[restore_path] = source
    return result


def _research_repositories(root: Path, research: Path) -> list[dict[str, Any]]:
    sources = _upstream_sources(root)
    discovered: list[Path] = []
    for current_text, directories, _files in os.walk(research, topdown=True, followlinks=False):
        current = Path(current_text)
        if ".git" in directories:
            discovered.append(current)
            directories.remove(".git")
    observed_paths = {repo.relative_to(root).as_posix() for repo in discovered}
    missing = sorted(set(sources) - observed_paths)
    unknown = sorted(observed_paths - set(sources))
    if missing:
        raise CleanupBlocked(f"upstream snapshots missing from .research: {', '.join(missing)}")
    if unknown:
        raise CleanupBlocked(f"unregistered nested repositories: {', '.join(unknown)}")

    repositories: list[dict[str, Any]] = []
    for repo in sorted(discovered, key=lambda item: item.as_posix()):
        relative = repo.relative_to(root).as_posix()
        source = sources[relative]
        status = _git(repo, "status", "--porcelain")
        if status:
            raise CleanupBlocked(f"nested research repository is dirty: {relative}: {status}")
        commit = _git(repo, "rev-parse", "HEAD")
        if commit != source.get("commit"):
            raise CleanupBlocked(f"snapshot commit mismatch for {relative}")
        observed_remote = _git(repo, "remote", "get-url", "origin", required=False)
        remote = str(source.get("remote", ""))
        if not remote:
            raise CleanupBlocked(f"missing restore remote for {relative}")
        if observed_remote and observed_remote != remote:
            raise CleanupBlocked(f"snapshot remote mismatch for {relative}")
        license_path = str(source.get("license_path", ""))
        if not license_path or not (repo / license_path).is_file():
            raise CleanupBlocked(f"missing recorded license for {relative}: {license_path}")
        repositories.append(
            {
                "path": relative,
                "remote": remote,
                "commit": commit,
                "license": source.get("license"),
                "license_path": license_path,
                "clean": True,
                "restore": [
                    f"git clone {remote} {relative}",
                    f"git -C {relative} checkout {commit}",
                ],
            }
        )
    return repositories


def _target(root: Path, path: Path, category: str) -> dict[str, Any]:
    absolute = _absolute_inside(root, path)
    _assert_no_reparse(root, absolute)
    digest, total_bytes, file_count = _path_fingerprint(root, absolute)
    result: dict[str, Any] = {
        "path": absolute.relative_to(root).as_posix(),
        "category": category,
        "kind": "directory" if absolute.is_dir() else "file",
        "bytes": total_bytes,
        "file_count": file_count,
        "sha256": digest,
        "backup_required": category in BACKUP_CATEGORIES,
    }
    if category == "research-snapshots":
        result["repositories"] = _research_repositories(root, absolute)
        result["restore"] = "Clone each recorded remote and checkout its recorded commit."
    elif category in BACKUP_CATEGORIES:
        result["restore"] = "Extract the verified cleanup backup archive."
    elif category == "tier-b-export":
        result["restore"] = "Re-export with scripts/tier_b_eval.py --export."
    else:
        result["restore"] = "Recreate by rerunning the owning local tool or test."
    return result


def build_cleanup_report(root: Path | str) -> dict[str, Any]:
    root_path = _root(root)
    candidates: list[tuple[Path, str]] = []

    fixed = (
        (root_path / ".research", "research-snapshots"),
        (root_path / ".test-tmp", "test-temp"),
        (root_path / ".hermes", "hermes-state"),
        (root_path / "reports", "historical-reports"),
    )
    candidates.extend((path, category) for path, category in fixed if path.exists() or path.is_symlink())
    for path in sorted(root_path.glob(".tmp-test-*"), key=lambda item: item.name.casefold()):
        if path.exists() or path.is_symlink():
            candidates.append((path, "test-temp"))

    evidence = root_path / "evidence"
    if evidence.is_dir():
        for path in sorted(evidence.glob("20260807-*"), key=lambda item: item.name.casefold()):
            if path.exists() or path.is_symlink():
                candidates.append((path, "dated-evidence"))

    candidate_paths = [path for path, _category in candidates]
    for path in _discover_cache_targets(root_path, candidate_paths):
        candidates.append((path, "python-cache"))
        candidate_paths.append(path)

    if evidence.is_dir():
        for path in sorted(evidence.rglob("tier-b-cases.jsonl"), key=lambda item: item.as_posix()):
            if path.is_file() and not _covered(path, candidate_paths):
                candidates.append((path, "tier-b-export"))
                candidate_paths.append(path)

    unique: dict[str, tuple[Path, str]] = {}
    for path, category in candidates:
        absolute = _absolute_inside(root_path, path)
        relative = absolute.relative_to(root_path).as_posix()
        if any(existing in absolute.parents for existing, _ in unique.values()):
            continue
        unique[relative] = (absolute, category)

    targets = [
        _target(root_path, path, category)
        for _relative, (path, category) in sorted(unique.items())
    ]
    token_material = json.dumps(
        [
            {key: target[key] for key in ("path", "category", "kind", "bytes", "file_count", "sha256")}
            for target in targets
        ],
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    approval_token = TOKEN_PREFIX + hashlib.sha256(token_material).hexdigest()[:16].upper()
    return {
        "_generated": GENERATED_MARKER,
        "schema_version": 1,
        "mode": "REPORT_ONLY",
        "root": str(root_path),
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "required_reviewer": REQUIRED_REVIEWER,
        "approval_token": approval_token,
        "targets": targets,
        "totals": {
            "targets": len(targets),
            "files": sum(target["file_count"] for target in targets),
            "bytes": sum(target["bytes"] for target in targets),
        },
        "backup": None,
        "application": None,
    }


def write_manifest(report: dict[str, Any], path: Path | str) -> Path:
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return output


def _sha256_file(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def create_backup_archive(
    root: Path | str, report: dict[str, Any], output: Path | str
) -> dict[str, Any]:
    root_path = _root(root)
    if report.get("root") != str(root_path):
        raise CleanupBlocked("backup report root does not match cleanup root")
    backup_path = Path(output).resolve()
    for target in report.get("targets", []):
        target_path = _absolute_inside(root_path, root_path / str(target.get("path", "")))
        if target_path == backup_path or target_path in backup_path.parents:
            raise CleanupBlocked("backup archive cannot be placed inside a cleanup target")
    backup_path.parent.mkdir(parents=True, exist_ok=True)
    included = [target for target in report.get("targets", []) if target.get("backup_required")]
    with zipfile.ZipFile(backup_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for target in included:
            target_path = _absolute_inside(root_path, root_path / target["path"])
            for _relative, kind, path in _tree_entries(root_path, target_path):
                if kind == "file":
                    archive.write(path, path.relative_to(root_path).as_posix())
    metadata = {
        "path": str(backup_path),
        "sha256": _sha256_file(backup_path),
        "targets": [target["path"] for target in included],
        "restore": f"Extract {backup_path} into {root_path}.",
    }
    report["backup"] = metadata
    return metadata


def _manifest(value: dict[str, Any] | Path | str) -> dict[str, Any]:
    if isinstance(value, dict):
        return value
    return json.loads(Path(value).read_text(encoding="utf-8"))


def _identity(target: dict[str, Any]) -> dict[str, Any]:
    return {
        key: target.get(key)
        for key in ("path", "category", "kind", "bytes", "file_count", "sha256")
    }


def _remove_readonly(function: Any, target: str, _error: Any) -> None:
    Path(target).chmod(stat.S_IWRITE)
    function(target)


def apply_cleanup(
    root: Path | str,
    manifest: dict[str, Any] | Path | str,
    *,
    reviewer: str,
    approval_token: str,
) -> dict[str, Any]:
    root_path = _root(root)
    payload = _manifest(manifest)
    if payload.get("mode") != "REPORT_ONLY":
        raise CleanupBlocked("cleanup manifest must originate from report-only mode")
    if payload.get("root") != str(root_path):
        raise CleanupBlocked("cleanup manifest root mismatch")
    if reviewer != payload.get("required_reviewer") or reviewer != REQUIRED_REVIEWER:
        raise CleanupBlocked(f"cleanup requires reviewer {REQUIRED_REVIEWER}")
    if approval_token != payload.get("approval_token"):
        raise CleanupBlocked("cleanup approval token mismatch")

    for target in payload.get("targets", []):
        candidate = _absolute_inside(root_path, root_path / str(target.get("path", "")))
        _assert_no_reparse(root_path, candidate)

    if any(target.get("backup_required") for target in payload.get("targets", [])):
        backup = payload.get("backup")
        if not isinstance(backup, dict):
            raise CleanupBlocked("verified backup archive is required before apply")
        backup_path = Path(str(backup.get("path", "")))
        if not backup_path.is_file() or _sha256_file(backup_path) != backup.get("sha256"):
            raise CleanupBlocked("cleanup backup archive is missing or changed")

    fresh = build_cleanup_report(root_path)
    expected = sorted((_identity(target) for target in payload.get("targets", [])), key=lambda item: item["path"])
    observed = sorted((_identity(target) for target in fresh.get("targets", [])), key=lambda item: item["path"])
    if expected != observed or fresh.get("approval_token") != approval_token:
        raise CleanupBlocked("cleanup targets changed after review; generate a new dry-run manifest")

    removed: list[str] = []
    for target in sorted(payload.get("targets", []), key=lambda item: item["path"], reverse=True):
        candidate = _absolute_inside(root_path, root_path / target["path"])
        _assert_no_reparse(root_path, candidate)
        if candidate.is_dir():
            shutil.rmtree(candidate, onerror=_remove_readonly)
        elif candidate.is_file():
            candidate.unlink()
        else:
            raise CleanupBlocked(f"reviewed cleanup target disappeared: {target['path']}")
        removed.append(target["path"])

    result = {
        "status": "APPLIED",
        "reviewer": reviewer,
        "approval_token": approval_token,
        "applied_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "removed": sorted(removed),
        "bytes": payload.get("totals", {}).get("bytes", 0),
        "backup": payload.get("backup"),
    }
    payload["application"] = result
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Report and apply the approved clean-template cleanup.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--backup", type=Path)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--reviewer")
    parser.add_argument("--approval-token")
    args = parser.parse_args(argv)

    if args.apply:
        if not args.manifest.exists():
            parser.error("--apply requires an existing --manifest")
        payload = _manifest(args.manifest)
        result = apply_cleanup(
            args.root,
            payload,
            reviewer=args.reviewer or "",
            approval_token=args.approval_token or "",
        )
        write_manifest(payload, args.manifest)
        print(json.dumps(result, indent=2))
        return 0

    report = build_cleanup_report(args.root)
    if args.backup:
        create_backup_archive(args.root, report, args.backup)
    write_manifest(report, args.manifest)
    print(
        json.dumps(
            {
                "mode": report["mode"],
                "manifest": str(args.manifest),
                "targets": report["totals"]["targets"],
                "files": report["totals"]["files"],
                "bytes": report["totals"]["bytes"],
                "approval_token": report["approval_token"],
                "backup": report["backup"],
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except CleanupBlocked as error:
        print(f"BLOCKED: {error}", file=sys.stderr)
        sys.exit(2)
