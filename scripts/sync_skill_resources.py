from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
try:
    from scripts.common import load_yaml
except ModuleNotFoundError:
    from common import load_yaml


GENERATED_HEADER = "# Generated by scripts/sync_skill_resources.py. Do not edit manually.\n\n"
SCRIPT_NAME = re.compile(r"^[a-z0-9_]+\.py$")


def _load_bundled_resources(root: Path) -> dict[str, list[str]]:
    registry_path = root / "registry" / "skill-resources.yaml"
    registry = load_yaml(registry_path)
    if not isinstance(registry, dict) or set(registry) != {
        "schema_version",
        "bundled",
        "repository_only",
    }:
        raise ValueError("skill resource registry has an invalid top-level schema")
    if registry.get("schema_version") != 1:
        raise ValueError("skill resource registry schema_version must be 1")

    normalized_sections: dict[str, dict[str, list[str]]] = {}
    for section in ("bundled", "repository_only"):
        mapping = registry.get(section)
        if not isinstance(mapping, dict):
            raise ValueError(f"skill resource registry {section} section must be a mapping")
        normalized: dict[str, list[str]] = {}
        for skill_id, script_names in sorted(mapping.items()):
            skill_path = root / "skills" / str(skill_id) / "SKILL.md"
            if not skill_path.is_file():
                raise ValueError(f"unknown skill in {section} resource registry: {skill_id}")
            if not isinstance(script_names, list) or not script_names:
                raise ValueError(f"{section} scripts for {skill_id} must be a non-empty list")
            names = [str(name) for name in script_names]
            if len(names) != len(set(names)):
                raise ValueError(f"duplicate {section} script for {skill_id}")
            for name in names:
                if not SCRIPT_NAME.fullmatch(name):
                    raise ValueError(f"invalid script name for {skill_id}: {name}")
                if not (root / "scripts" / name).is_file():
                    raise ValueError(f"missing source script for {skill_id}: scripts/{name}")
            normalized[str(skill_id)] = sorted(names)
        normalized_sections[section] = normalized
    return normalized_sections["bundled"]


def sync_skill_resources(root: Path | str, *, check: bool = False) -> list[Path]:
    root_path = Path(root).resolve()
    bundled = _load_bundled_resources(root_path)
    expected_paths: set[Path] = set()
    drift: list[Path] = []

    for skill_id, script_names in bundled.items():
        destination_root = root_path / "skills" / skill_id / "scripts"
        for script_name in script_names:
            source = root_path / "scripts" / script_name
            destination = destination_root / script_name
            expected_paths.add(destination)
            expected = GENERATED_HEADER + source.read_text(encoding="utf-8")
            observed = destination.read_text(encoding="utf-8") if destination.is_file() else None
            if observed == expected:
                continue
            drift.append(destination)
            if not check:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(expected, encoding="utf-8")

    for generated in sorted((root_path / "skills").glob("*/scripts/*.py")):
        if generated in expected_paths:
            continue
        body = generated.read_text(encoding="utf-8")
        if not body.startswith(GENERATED_HEADER):
            continue
        drift.append(generated)
        if not check:
            generated.unlink()

    return sorted(set(drift))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Synchronize standalone helper scripts into canonical skill folders."
    )
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--check", action="store_true", help="report drift without writing files")
    args = parser.parse_args(argv)

    try:
        drift = sync_skill_resources(args.root, check=args.check)
    except (OSError, ValueError) as error:
        print(f"skill-resources: ERROR: {error}")
        return 1

    root = Path(args.root).resolve()
    for path in drift:
        print(path.relative_to(root).as_posix())
    if args.check and drift:
        print(f"skill-resources: {len(drift)} generated file(s) out of sync")
        return 1
    action = "synced" if drift else "already in sync"
    print(f"skill-resources: {len(drift)} generated file(s) {action}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
