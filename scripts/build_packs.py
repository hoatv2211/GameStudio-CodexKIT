MARKER = "Generated by scripts/build_packs.py. Do not edit manually."
_SYNC_RESOURCE_JSON_COMMENT = (
    "Generated by scripts/sync_skill_resources.py. Do not edit manually."
)
_SAFE_COMPONENT = re.compile(r"^[a-z0-9][a-z0-9-]*$")


@dataclass(frozen=True)
class _CapturedSource:
    path: Path
    data: bytes


@dataclass(frozen=True)
class _TreeSnapshot:
    files: tuple[tuple[str, str], ...]


class _ManualRecoveryRequired(RuntimeError):
    pass


def _is_reparse_point(path: Path) -> bool:
    try:
        info = path.lstat()
    except FileNotFoundError:
        return False
    attributes = getattr(info, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return path.is_symlink() or bool(attributes & reparse_flag)


def _assert_no_reparse_path(path: Path) -> None:
    absolute = Path(os.path.abspath(str(path)))
    for candidate in [*list(absolute.parents)[::-1], absolute]:
        if _is_reparse_point(candidate):
            raise ValueError(f"symlink or reparse point is not allowed: {candidate}")


def _safe_component(value: object, label: str) -> str:
    if not isinstance(value, str) or _SAFE_COMPONENT.fullmatch(value) is None:
        raise ValueError(f"unsafe {label}: {value}")
    return value


def _safe_skill_source(root: Path, skill_name: object) -> Path:
    name = _safe_component(skill_name, "pack skill")
    root = root.resolve()
    skills_root = root / "skills"
    _assert_no_reparse_path(root)
    _assert_no_reparse_path(skills_root)
    if not skills_root.is_dir():
        raise ValueError(f"canonical skills root is missing: {skills_root}")
    source = skills_root / name
    _assert_no_reparse_path(source)
    if not source.is_dir():
        raise ValueError(f"pack skill source is missing: {name}")
    try:
        source.resolve().relative_to(skills_root.resolve())
    except ValueError as error:
        raise ValueError(f"pack skill source escapes canonical skills: {name}") from error
    if not (source / "SKILL.md").is_file():
        raise ValueError(f"pack skill source has no SKILL.md: {name}")
    return source


def _safe_destination(base: Path, relative: PurePosixPath | str) -> Path:
    relative_path = PurePosixPath(str(relative).replace("\\", "/"))
    if relative_path.is_absolute() or not relative_path.parts or ".." in relative_path.parts:
        raise ValueError(f"unsafe generated destination: {relative}")
    _assert_no_reparse_path(base)
    current = base
    for part in relative_path.parts:
        current = current / part
        if _is_reparse_point(current):
            raise ValueError(f"symlink or reparse point is not allowed: {current}")
    try:
        current.resolve().relative_to(base.resolve())
    except ValueError as error:
        raise ValueError(f"generated destination escapes its stage: {relative}") from error
    return current


def _generated_skill(text: str) -> str:
    opening = re.match(r"\A---\s*\r?\n", text)
    if opening is None:
        raise ValueError("SKILL.md must start with YAML frontmatter")
    return f"---\n# {MARKER}\n{text[opening.end():]}"


def _reject_duplicate_json_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    parsed: dict[str, Any] = {}
    for key, value in pairs:
        if key in parsed:
            raise ValueError(f"duplicate JSON key: {key}")
        parsed[key] = value
    return parsed


def _reject_nonstandard_json_constant(value: str) -> None:
    raise ValueError(f"non-standard JSON constant: {value}")


def _parse_json_object(text: str, path: Path) -> dict[str, Any]:
    try:
        parsed = json.loads(
            text,
            object_pairs_hook=_reject_duplicate_json_keys,
            parse_constant=_reject_nonstandard_json_constant,
        )
    except json.JSONDecodeError as error:
        raise ValueError(f"invalid JSON resource: {path}") from error
    if not isinstance(parsed, dict):
        raise ValueError(f"JSON resource must be a JSON object: {path}")
    return parsed


def _generated_json(text: str, path: Path) -> str:
    parsed = _parse_json_object(text, path)
    existing_comment = parsed.get("$comment")
    if "$comment" in parsed and existing_comment not in {
        MARKER,
        _SYNC_RESOURCE_JSON_COMMENT,
    }:
        raise ValueError(f"incompatible JSON $comment in resource: {path}")
    generated = {"$comment": MARKER}
    generated.update(
        (key, value) for key, value in parsed.items() if key != "$comment"
    )
    return json.dumps(generated, indent=2) + "\n"


def _generated_resource(source: Path | _CapturedSource) -> str:
    path = source.path if isinstance(source, _CapturedSource) else source
    data = source.data if isinstance(source, _CapturedSource) else path.read_bytes()
    text = data.decode("utf-8")
    if path.name == "SKILL.md":
        return _generated_skill(text)
    if path.suffix.casefold() == ".json":
        return _generated_json(text, path)
    if path.suffix.casefold() in {".py", ".sh", ".ps1", ".yaml", ".yml", ".toml"}:
        return f"# {MARKER}\n\n{text}"
    if path.suffix.casefold() in {".md", ".txt"}:
        return f"<!-- {MARKER} -->\n{text}"
    raise ValueError(f"unsupported skill resource type: {path}")


def _is_generated_artifact(path: Path, text: str) -> bool:
    lines = text.splitlines()
    if path.name == "manifest.json":
        try:
            manifest = json.loads(text)
        except json.JSONDecodeError:
            return False
        return isinstance(manifest, dict) and manifest.get("_generated") == MARKER
    if path.suffix.casefold() == ".json":
        try:
            resource = _parse_json_object(text, path)
        except ValueError:
            return False
        return resource.get("$comment") == MARKER
    if path.name == "SKILL.md":
        return len(lines) > 1 and lines[0] == "---" and lines[1] == f"# {MARKER}"
    if path.suffix.casefold() in {".py", ".sh", ".ps1", ".yaml", ".yml", ".toml"}:
        return bool(lines) and lines[0] == f"# {MARKER}"
    if path.suffix.casefold() in {".md", ".txt"}:
        return bool(lines) and lines[0] == f"<!-- {MARKER} -->"
    return False


def _assert_disjoint_output(output: Path, source_roots: list[Path]) -> None:
    resolved_output = output.resolve()
    for source_root in source_roots:
        resolved_source = source_root.resolve()
        if (
            resolved_output == resolved_source
            or resolved_output.is_relative_to(resolved_source)
            or resolved_source.is_relative_to(resolved_output)
        ):
            raise ValueError(
                f"pack output overlaps canonical skills: {resolved_output} and {resolved_source}"
            )


def _stat_identity(info: os.stat_result) -> tuple[int, int, int, int, int, int]:
    return (
        info.st_dev,
        info.st_ino,
        info.st_mode,
        info.st_size,
        info.st_mtime_ns,
        info.st_ctime_ns,
    )


def _listing_identity(info: os.stat_result) -> tuple[int, int, int, int]:
    return (info.st_mode, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def _is_reparse_info(info: os.stat_result) -> bool:
    attributes = getattr(info, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return bool(attributes & reparse_flag)


def _capture_source_file(path: Path, expected: os.stat_result) -> _CapturedSource:
    if _is_reparse_info(expected) or not stat.S_ISREG(expected.st_mode):
        raise ValueError(f"source file is not a safe regular file: {path}")
    flags = os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError as error:
        raise ValueError(f"source file changed during capture: {path}") from error
    try:
        opened_before = os.fstat(descriptor)
        path_before = path.lstat()
        if (
            _is_reparse_info(path_before)
            or _listing_identity(expected) != _listing_identity(path_before)
            or _stat_identity(opened_before) != _stat_identity(path_before)
        ):
            raise ValueError(f"source file changed during capture: {path}")
        with os.fdopen(descriptor, "rb", closefd=False) as stream:
            data = stream.read()
        opened_after = os.fstat(descriptor)
        path_after = path.lstat()
        if (
            _is_reparse_info(path_after)
            or _stat_identity(opened_before) != _stat_identity(opened_after)
            or _stat_identity(opened_after) != _stat_identity(path_after)
        ):
            raise ValueError(f"source file changed during capture: {path}")
    finally:
        os.close(descriptor)
    return _CapturedSource(path=path, data=data)


def _walk_files(
    path: Path,
    *,
    reject_empty_directories: bool,
    ignore_runtime_cache: bool = False,
) -> list[Path] | list[_CapturedSource]:
    _assert_no_reparse_path(path)
    if not path.is_dir():
        raise RuntimeError(f"managed pack output is not a directory: {path}")
    root_info = path.lstat()
    if _is_reparse_info(root_info) or not stat.S_ISDIR(root_info.st_mode):
        raise ValueError(f"pack directory is not a safe real directory: {path}")
    files: list[Path] = []
    captured: list[_CapturedSource] = []
    pending = [(path, root_info)]
    while pending:
        current, queued_info = pending.pop()
        _assert_no_reparse_path(current)
        current_info = current.lstat()
        if (
            _is_reparse_info(current_info)
            or not stat.S_ISDIR(current_info.st_mode)
            or _stat_identity(current_info) != _stat_identity(queued_info)
        ):
            raise ValueError(f"pack directory changed before scan: {current}")
        entries = list(os.scandir(current))
        # Windows traversal is not directory-handle-bound, so fail closed on lexical drift.
        _assert_no_reparse_path(current)
        post_scan_info = current.lstat()
        if (
            _is_reparse_info(post_scan_info)
            or not stat.S_ISDIR(post_scan_info.st_mode)
            or _stat_identity(post_scan_info) != _stat_identity(queued_info)
        ):
            raise ValueError(f"pack directory changed during scan: {current}")
        if not entries and current != path and reject_empty_directories:
            raise RuntimeError(f"refusing to remove unmanaged directory: {current}")
        for entry in entries:
            candidate = Path(entry.path)
            info = entry.stat(follow_symlinks=False)
            attributes = getattr(info, "st_file_attributes", 0)
            reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
            if entry.is_symlink() or bool(attributes & reparse_flag):
                raise ValueError(f"symlink or reparse point is not allowed: {candidate}")
            _assert_no_reparse_path(candidate)
            candidate_info = candidate.lstat()
            if _is_reparse_info(candidate_info):
                raise ValueError(f"symlink or reparse point is not allowed: {candidate}")
            if entry.is_dir(follow_symlinks=False):
                if ignore_runtime_cache and entry.name == "__pycache__":
                    continue
                queued_candidate = candidate.lstat()
                if (
                    _is_reparse_info(queued_candidate)
                    or not stat.S_ISDIR(queued_candidate.st_mode)
                ):
                    raise ValueError(f"pack directory changed while queued: {candidate}")
                pending.append((candidate, queued_candidate))
            elif entry.is_file(follow_symlinks=False):
                if not stat.S_ISREG(candidate_info.st_mode):
                    raise ValueError(f"pack file changed while scanned: {candidate}")
                if ignore_runtime_cache and candidate.suffix.casefold() == ".pyc":
                    continue
                if ignore_runtime_cache:
                    captured.append(_capture_source_file(candidate, info))
                else:
                    files.append(candidate)
            else:
                raise RuntimeError(f"unsupported managed pack entry: {candidate}")
    if ignore_runtime_cache:
        return sorted(captured, key=lambda item: item.path.relative_to(path).as_posix())
    return sorted(files, key=lambda item: item.relative_to(path).as_posix())


def _tree_snapshot(path: Path) -> _TreeSnapshot:
    files = _walk_files(path, reject_empty_directories=True)
    assert all(isinstance(file, Path) for file in files)
    return _TreeSnapshot(
        files=tuple(
            sorted(
                (
                    file.relative_to(path).as_posix(),
                    hashlib.sha256(file.read_bytes()).hexdigest(),
                )
                for file in files
            )
        )
    )


def _snapshot_from_contents(contents: list[tuple[str, str]]) -> _TreeSnapshot:
    return _TreeSnapshot(
        files=tuple(
            sorted(
                (relative, hashlib.sha256(content.encode("utf-8")).hexdigest())
                for relative, content in contents
            )
        )
    )


def _snapshot_payload(snapshot: _TreeSnapshot) -> list[dict[str, str]]:
    return [{"path": path, "sha256": digest} for path, digest in snapshot.files]


def _snapshot_from_payload(payload: object) -> _TreeSnapshot:
    if not isinstance(payload, list):
        raise ValueError("swap recovery snapshot must be a list")
    files: list[tuple[str, str]] = []
    for item in payload:
        if not isinstance(item, dict):
            raise ValueError("swap recovery snapshot entries must be objects")
        relative = item.get("path")
        digest = item.get("sha256")
        if (
            not isinstance(relative, str)
            or not isinstance(digest, str)
            or re.fullmatch(r"[0-9a-f]{64}", digest) is None
        ):
            raise ValueError("swap recovery snapshot entry is invalid")
        files.append((relative, digest))
    if len({path for path, _digest in files}) != len(files):
        raise ValueError("swap recovery snapshot contains duplicate paths")
    return _TreeSnapshot(files=tuple(sorted(files)))


def _validate_generated_tree(
    path: Path,
    *,
    expected_files: list[str] | None = None,
    expected_snapshot: _TreeSnapshot | None = None,
) -> _TreeSnapshot:
    files = _walk_files(path, reject_empty_directories=True)
    assert all(isinstance(file, Path) for file in files)
    actual = sorted(file.relative_to(path).as_posix() for file in files)
    if "manifest.json" not in actual:
        raise RuntimeError(f"generated pack manifest is missing: {path}")
    for file in files:
        text = file.read_text(encoding="utf-8", errors="replace")
        if not _is_generated_artifact(file, text):
            raise RuntimeError(f"generated pack contains unmanaged artifact: {file}")
    manifest = json.loads((path / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("_generated") != MARKER:
        raise RuntimeError(f"generated pack manifest is not owned: {path / 'manifest.json'}")
    declared = manifest.get("files")
    actual_without_manifest = [item for item in actual if item != "manifest.json"]
    if declared is not None and sorted(declared) != actual_without_manifest:
        raise RuntimeError(f"generated pack manifest file ownership mismatch: {path / 'manifest.json'}")
    if expected_files is not None and sorted(expected_files) != actual_without_manifest:
        raise RuntimeError(f"generated pack render file set mismatch: {path}")
    snapshot = _tree_snapshot(path)
    if expected_snapshot is not None and snapshot != expected_snapshot:
        raise RuntimeError(f"generated pack render hash mismatch: {path}")
    return snapshot


def _validate_existing_output(path: Path) -> _TreeSnapshot | None:
    if not path.exists() and not path.is_symlink():
        return None
    return _validate_generated_tree(path)


def _owned_temp_path(output: Path, suffix: str) -> Path:
    return output.parent / f".{output.name}.{uuid.uuid4().hex}.{suffix}"


def _is_owned_temp_path(path: Path, output: Path, suffix: str) -> bool:
    owned_name = re.compile(
        rf"^\.{re.escape(output.name)}\.[0-9a-f]{{32}}\.{re.escape(suffix)}$"
    )
    return path.parent == output.parent and owned_name.fullmatch(path.name) is not None


def _validate_owned_temp(
    path: Path,
    output: Path,
    suffix: str,
    expected_snapshot: _TreeSnapshot,
) -> None:
    if not _is_owned_temp_path(path, output, suffix):
        raise RuntimeError(f"refusing to remove unowned pack temporary path: {path}")
    if path.exists() or path.is_symlink():
        try:
            _assert_no_reparse_path(path)
            if not path.is_dir() or _tree_snapshot(path) != expected_snapshot:
                raise ValueError("snapshot mismatch")
        except (OSError, RuntimeError, ValueError) as error:
            raise _ManualRecoveryRequired(
                f"manual recovery required; preserving changed pack temporary path: {path}"
            ) from error


def _swap_recovery_path(output: Path) -> Path:
    return output.parent / f".{output.name}.swap-recovery.json"


def _write_swap_recovery(
    output: Path,
    rollback: Path | None,
    stage: Path,
    previous_snapshot: _TreeSnapshot | None,
    staged_snapshot: _TreeSnapshot,
    *,
    state: str = "prepared",
) -> Path:
    recovery_path = _swap_recovery_path(output)
    payload = {
        "_generated": MARKER,
        "schema_version": 1,
        "kind": "pack-output-swap-recovery",
        "state": state,
        "output": str(output),
        "rollback": str(rollback) if rollback is not None else None,
        "stage": str(stage),
        "previous_files": (
            _snapshot_payload(previous_snapshot) if previous_snapshot is not None else None
        ),
        "staged_files": _snapshot_payload(staged_snapshot),
    }
    encoded = (json.dumps(payload, indent=2) + "\n").encode("utf-8")
    try:
        with recovery_path.open("xb") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
    except FileExistsError:
        if recovery_path.read_bytes() == encoded:
            return recovery_path
        raise _ManualRecoveryRequired(
            f"manual recovery required; pack recovery evidence drifted: {recovery_path}"
        ) from None
    except OSError as error:
        raise _ManualRecoveryRequired(
            "swap recovery journal could not be persisted; "
            f"output={output} rollback={rollback} stage={stage}"
        ) from error
    return recovery_path


def _update_swap_recovery(
    output: Path,
    rollback: Path | None,
    stage: Path,
    previous_snapshot: _TreeSnapshot | None,
    staged_snapshot: _TreeSnapshot,
    *,
    expected_states: set[str],
    state: str,
) -> Path:
    recovery_path = _swap_recovery_path(output)
    try:
        current = json.loads(recovery_path.read_text(encoding="utf-8"))
        if not isinstance(current, dict) or current.get("state") not in expected_states:
            raise ValueError("unexpected recovery state")
        expected_current = {
            **current,
            "state": current["state"],
        }
        identity_fields = {
            "_generated": MARKER,
            "schema_version": 1,
            "kind": "pack-output-swap-recovery",
            "output": str(output),
            "rollback": str(rollback) if rollback is not None else None,
            "stage": str(stage),
            "previous_files": (
                _snapshot_payload(previous_snapshot)
                if previous_snapshot is not None
                else None
            ),
            "staged_files": _snapshot_payload(staged_snapshot),
        }
        if {key: current.get(key) for key in identity_fields} != identity_fields:
            raise ValueError("recovery identity changed")
        updated = {**expected_current, "state": state}
        _write_manifest(recovery_path, updated)
        if json.loads(recovery_path.read_text(encoding="utf-8")) != updated:
            raise ValueError("recovery state verification failed")
    except (OSError, ValueError, json.JSONDecodeError) as error:
        raise _ManualRecoveryRequired(
            f"manual recovery required; pack recovery state update failed: {recovery_path}"
        ) from error
    return recovery_path


def _swap_completion_payload(
    output: Path,
    rollback: Path,
    stage: Path,
    previous_snapshot: _TreeSnapshot,
    staged_snapshot: _TreeSnapshot,
) -> dict[str, object]:
    return {
        "_generated": MARKER,
        "schema_version": 1,
        "kind": "pack-output-swap-completion",
        "status": "published",
        "output": str(output),
        "rollback": str(rollback),
        "stage": str(stage),
        "previous_files": _snapshot_payload(previous_snapshot),
        "staged_files": _snapshot_payload(staged_snapshot),
    }


def _write_swap_completion(
    output: Path,
    rollback: Path,
    stage: Path,
    previous_snapshot: _TreeSnapshot,
    staged_snapshot: _TreeSnapshot,
) -> Path:
    payload = _swap_completion_payload(
        output,
        rollback,
        stage,
        previous_snapshot,
        staged_snapshot,
    )
    encoded = (json.dumps(payload, indent=2) + "\n").encode("utf-8")
    digest = hashlib.sha256(encoded).hexdigest()
    completion_path = output.parent / f".{output.name}.{digest}.swap-completion.json"
    try:
        with completion_path.open("xb") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
    except FileExistsError:
        if completion_path.read_bytes() != encoded:
            raise _ManualRecoveryRequired(
                f"manual recovery required; pack completion evidence drifted: {completion_path}"
            ) from None
    return completion_path


def _archive_swap_recovery(
    output: Path,
    recovery_path: Path,
    expected_bytes: bytes,
) -> Path:
    digest = hashlib.sha256(expected_bytes).hexdigest()
    archived = output.parent / f".{output.name}.{digest}.swap-recovery.json"
    try:
        if recovery_path.read_bytes() != expected_bytes:
            raise ValueError("recovery journal changed before archive")
        _atomic_rename_no_replace(recovery_path, archived)
        if archived.read_bytes() != expected_bytes:
            raise ValueError("recovery journal changed during archive")
    except (OSError, ValueError) as error:
        raise _ManualRecoveryRequired(
            f"manual recovery required; pack recovery archive failed: {recovery_path}"
        ) from error
    return archived


def _preserve_swap_failure(
    output: Path,
    rollback: Path | None,
    stage: Path,
    previous_snapshot: _TreeSnapshot | None,
    staged_snapshot: _TreeSnapshot,
    error: BaseException,
) -> None:
    # Failure cleanup is deliberately non-destructive: snapshot validation is not
    # a safe authority for a later recursive delete if another process swaps paths.
    try:
        _validate_owned_temp(stage, output, "stage", staged_snapshot)
    except _ManualRecoveryRequired:
        pass
    recovery_path = _swap_recovery_path(output)
    if not recovery_path.exists():
        recovery_path = _write_swap_recovery(
            output,
            rollback,
            stage,
            previous_snapshot,
            staged_snapshot,
        )
    raise _ManualRecoveryRequired(f"swap recovery required: {recovery_path}") from error


def _recover_swap_if_needed(output: Path) -> None:
    recovery_path = _swap_recovery_path(output)
    if not recovery_path.exists():
        return
    try:
        recovery_bytes = recovery_path.read_bytes()
        recovery = json.loads(recovery_bytes.decode("utf-8"))
        if (
            not isinstance(recovery, dict)
            or recovery.get("_generated") != MARKER
            or recovery.get("kind") != "pack-output-swap-recovery"
            or recovery.get("output") != str(output)
        ):
            raise ValueError("invalid recovery header")
        rollback_value = recovery.get("rollback")
        rollback = Path(rollback_value) if isinstance(rollback_value, str) else None
        stage = Path(str(recovery["stage"]))
        if (
            (rollback is not None and not _is_owned_temp_path(rollback, output, "rollback"))
            or not _is_owned_temp_path(stage, output, "stage")
        ):
            raise ValueError("recovery paths are outside owned scope")
        previous_payload = recovery.get("previous_files")
        previous_snapshot = (
            _snapshot_from_payload(previous_payload) if previous_payload is not None else None
        )
        staged_snapshot = _snapshot_from_payload(recovery.get("staged_files"))
        if (previous_snapshot is None) != (rollback is None):
            raise ValueError("recovery rollback and previous snapshot disagree")
        recovery_state = recovery.get("state")
        if recovery_state not in {"prepared", "output-moved", "restored", "published"}:
            raise ValueError("invalid recovery state")
    except (KeyError, OSError, ValueError, json.JSONDecodeError) as error:
        raise _ManualRecoveryRequired(
            f"manual recovery required; invalid pack swap recovery: {recovery_path}"
        ) from error

    def snapshot_or_manual(path: Path, label: str) -> _TreeSnapshot:
        try:
            return _tree_snapshot(path)
        except Exception as error:
            raise _ManualRecoveryRequired(
                f"manual recovery required; {label} tree is missing or drifted: {path}"
            ) from error

    if previous_snapshot is None:
        if output.exists():
            output_snapshot = snapshot_or_manual(output, "pack output")
            if output_snapshot != staged_snapshot or stage.exists():
                raise _ManualRecoveryRequired(
                    f"manual recovery required; pack output drifted during recovery: {output}"
                )
            if recovery_state != "published":
                _update_swap_recovery(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    expected_states={recovery_state},
                    state="published",
                )
                recovery_bytes = recovery_path.read_bytes()
        else:
            if not stage.exists():
                raise _ManualRecoveryRequired(
                    f"manual recovery required; pack stage is missing: {stage}"
                )
            _validate_owned_temp(stage, output, "stage", staged_snapshot)
        _archive_swap_recovery(output, recovery_path, recovery_bytes)
        return

    assert rollback is not None
    if output.exists():
        output_snapshot = snapshot_or_manual(output, "pack output")
        if output_snapshot == previous_snapshot:
            if rollback.exists():
                raise _ManualRecoveryRequired(
                    f"manual recovery required; duplicate previous pack tree: {rollback}"
                )
            if stage.exists():
                _validate_owned_temp(stage, output, "stage", staged_snapshot)
            else:
                raise _ManualRecoveryRequired(
                    f"manual recovery required; pack stage is missing: {stage}"
                )
            if recovery_state == "output-moved":
                _update_swap_recovery(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    expected_states={"output-moved"},
                    state="restored",
                )
                recovery_bytes = recovery_path.read_bytes()
            _archive_swap_recovery(output, recovery_path, recovery_bytes)
            return
        elif output_snapshot == staged_snapshot:
            if stage.exists():
                raise _ManualRecoveryRequired(
                    f"manual recovery required; duplicate staged pack tree: {stage}"
                )
            if rollback.exists():
                _validate_owned_temp(rollback, output, "rollback", previous_snapshot)
                _write_swap_completion(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                )
            else:
                raise _ManualRecoveryRequired(
                    f"manual recovery required; pack rollback is missing: {rollback}"
                )
            if recovery_state != "published":
                _update_swap_recovery(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    expected_states={recovery_state},
                    state="published",
                )
                recovery_bytes = recovery_path.read_bytes()
            _archive_swap_recovery(output, recovery_path, recovery_bytes)
            return
        else:
            raise _ManualRecoveryRequired(
                f"manual recovery required; pack output drifted during recovery: {output}"
            )
    else:
        if not rollback.exists() or snapshot_or_manual(rollback, "pack rollback") != previous_snapshot:
            raise _ManualRecoveryRequired(
                f"manual recovery required; pack rollback is missing or drifted: {rollback}"
            )
        try:
            _rename_owned_directory(rollback, output)
        except OSError as error:
            raise _ManualRecoveryRequired(
                f"manual recovery required; pack rollback restore failed: {rollback}"
            ) from error
        if snapshot_or_manual(output, "restored pack output") != previous_snapshot:
            raise _ManualRecoveryRequired(
                f"manual recovery required; restored pack output failed validation: {output}"
            )
        _update_swap_recovery(
            output,
            rollback,
            stage,
            previous_snapshot,
            staged_snapshot,
            expected_states={recovery_state},
            state="restored",
        )
        recovery_bytes = recovery_path.read_bytes()
        if stage.exists():
            _validate_owned_temp(stage, output, "stage", staged_snapshot)
        else:
            raise _ManualRecoveryRequired(
                f"manual recovery required; pack stage is missing: {stage}"
            )
        _archive_swap_recovery(output, recovery_path, recovery_bytes)


def _missing_ancestors(path: Path) -> list[Path]:
    missing: list[Path] = []
    cursor = Path(os.path.abspath(str(path)))
    while not cursor.exists():
        missing.append(cursor)
        cursor = cursor.parent
    return missing


def _cleanup_created_ancestors(paths: list[Path]) -> None:
    for path in paths:
        try:
            path.rmdir()
        except OSError:
            break


def _rename_owned_directory(source: Path, target: Path) -> Path:
    _atomic_rename_no_replace(source, target)
    return target


def _swap_stage(
    stage: Path,
    output: Path,
    staged_snapshot: _TreeSnapshot,
    previous_snapshot: _TreeSnapshot | None,
) -> None:
    # Keep the previous tree recoverable until the staged tree is visible.
    rollback = _owned_temp_path(output, "rollback") if previous_snapshot is not None else None
    recovery_path = _write_swap_recovery(
        output,
        rollback,
        stage,
        previous_snapshot,
        staged_snapshot,
        state="prepared",
    )
    if output.exists():
        if previous_snapshot is None:
            raise RuntimeError(f"managed pack output snapshot is missing: {output}")
        assert rollback is not None
        try:
            _rename_owned_directory(output, rollback)
        except BaseException as rename_error:
            _preserve_swap_failure(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                rename_error,
            )
        _update_swap_recovery(
            output,
            rollback,
            stage,
            previous_snapshot,
            staged_snapshot,
            expected_states={"prepared"},
            state="output-moved",
        )
        try:
            rollback_snapshot = _tree_snapshot(rollback)
        except Exception as validation_error:
            try:
                _rename_owned_directory(rollback, output)
            except BaseException as restore_error:
                _preserve_swap_failure(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    restore_error,
                )
            _update_swap_recovery(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                expected_states={"output-moved"},
                state="restored",
            )
            _preserve_swap_failure(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                validation_error,
            )
        if rollback_snapshot != previous_snapshot:
            try:
                _rename_owned_directory(rollback, output)
            except BaseException as restore_error:
                _preserve_swap_failure(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    restore_error,
                )
            _update_swap_recovery(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                expected_states={"output-moved"},
                state="restored",
            )
            _preserve_swap_failure(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                RuntimeError(f"managed pack output changed before swap: {output}"),
            )
    try:
        _rename_owned_directory(stage, output)
    except BaseException as publish_error:
        if rollback is not None and rollback.exists() and not output.exists():
            try:
                _rename_owned_directory(rollback, output)
            except BaseException as restore_error:
                _preserve_swap_failure(
                    output,
                    rollback,
                    stage,
                    previous_snapshot,
                    staged_snapshot,
                    restore_error,
                )
            _update_swap_recovery(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                expected_states={"output-moved"},
                state="restored",
            )
        _preserve_swap_failure(
            output,
            rollback,
            stage,
            previous_snapshot,
            staged_snapshot,
            publish_error,
        )
    _update_swap_recovery(
        output,
        rollback,
        stage,
        previous_snapshot,
        staged_snapshot,
        expected_states={"prepared", "output-moved"},
        state="published",
    )
    try:
        published_snapshot = _tree_snapshot(output)
    except Exception as validation_error:
        raise _ManualRecoveryRequired(f"swap recovery required: {recovery_path}") from validation_error
    if published_snapshot != staged_snapshot:
        raise _ManualRecoveryRequired(
            f"swap recovery required: {recovery_path}"
        )
    if rollback is not None and rollback.exists():
        assert previous_snapshot is not None
        _validate_owned_temp(rollback, output, "rollback", previous_snapshot)
        try:
            _write_swap_completion(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
            )
        except BaseException as completion_error:
            raise _ManualRecoveryRequired(
                f"swap recovery required: {recovery_path}"
            ) from completion_error
    _archive_swap_recovery(output, recovery_path, recovery_path.read_bytes())


def _render_pack_stage(
    output: Path,
    generated: list[tuple[str, str]],
    manifest: dict[str, Any],
    previous_snapshot: _TreeSnapshot | None,
) -> list[str]:
    manifest_text = json.dumps(manifest, indent=2) + "\n"
    staged_snapshot = _snapshot_from_contents(
        [*generated, ("manifest.json", manifest_text)]
    )
    expected = [relative for relative, _content in generated]
    if previous_snapshot == staged_snapshot:
        return sorted([*expected, "manifest.json"])
    stage = _owned_temp_path(output, "stage")
    stage.mkdir(parents=False, exist_ok=False)
    try:
        for relative, content in generated:
            destination = _safe_destination(stage, relative)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8", newline="\n")
        manifest_path = _safe_destination(stage, "manifest.json")
        manifest_path.write_text(manifest_text, encoding="utf-8", newline="\n")
        _validate_generated_tree(
            stage,
            expected_files=expected,
            expected_snapshot=staged_snapshot,
        )
        _swap_stage(stage, output, staged_snapshot, previous_snapshot)
        return sorted([*expected, "manifest.json"])
    except _ManualRecoveryRequired:
        raise
    except BaseException as render_error:
        if stage.exists():
            rollback = _owned_temp_path(output, "rollback") if previous_snapshot is not None else None
            _preserve_swap_failure(
                output,
                rollback,
                stage,
                previous_snapshot,
                staged_snapshot,
                render_error,
            )
        raise


def _pack_plan(
    root_path: Path,
    pack: dict[str, Any],
    output_root: Path | str,
    *,
    packs: list[dict[str, Any]],
    capabilities: list[dict[str, Any]],
) -> tuple[
    Path,
    list[tuple[str, str]],
    dict[str, Any],
    _TreeSnapshot | None,
]:
    pack_id = _safe_component(pack.get("id"), "pack id")
    declared = pack.get("skills")
    if not isinstance(declared, list) or not declared:
        raise ValueError(f"pack {pack_id} must declare skills")
    declared_skills = [_safe_component(value, "pack skill") for value in declared]
    resolved_skills = resolve_pack_skill_closure(packs, capabilities, pack_id)
    source_roots = [_safe_skill_source(root_path, skill_name) for skill_name in resolved_skills]
    if len(set(declared_skills)) != len(declared_skills):
        raise ValueError(f"pack {pack_id} contains duplicate skill ids")
    depends_on = pack.get("depends_on", [])
    if not isinstance(depends_on, list):
        raise ValueError(f"pack {pack_id} depends_on must be a list")
    normalized_dependencies = [
        _safe_component(dependency, "pack dependency") for dependency in depends_on
    ]
    output_root_path = Path(output_root).absolute()
    _assert_no_reparse_path(output_root_path)
    output = output_root_path.resolve() / pack_id
    _assert_disjoint_output(output, [root_path / "skills"])
    _recover_swap_if_needed(output)
    previous_snapshot = _validate_existing_output(output)
    generated: list[tuple[str, str]] = []
    digest = hashlib.sha256()
    for resolved_skill, source_root in zip(resolved_skills, source_roots):
        captured_sources = _walk_files(
            source_root,
            reject_empty_directories=False,
            ignore_runtime_cache=True,
        )
        assert all(isinstance(source, _CapturedSource) for source in captured_sources)
        for source in captured_sources:
            relative_resource = source.path.relative_to(source_root)
            source_bytes = source.data
            digest.update(resolved_skill.encode("utf-8"))
            digest.update(relative_resource.as_posix().encode("utf-8"))
            digest.update(source_bytes)
            relative = PurePosixPath("skills", resolved_skill, *relative_resource.parts).as_posix()
            generated.append((relative, _generated_resource(source)))
    generated = sorted(generated, key=lambda item: item[0])
    manifest = {
        "_generated": MARKER,
        "schema_version": 1,
        "pack": pack_id,
        "description": pack.get("description", ""),
        "depends_on": normalized_dependencies,
        "declared_skills": declared_skills,
        "skills": resolved_skills,
        "source_digest": digest.hexdigest(),
        "files": [relative for relative, _content in generated],
    }
    return output, generated, manifest, previous_snapshot


def _publish_pack_plan(
    output: Path,
    generated: list[tuple[str, str]],
    manifest: dict[str, Any],
    previous_snapshot: _TreeSnapshot | None,
) -> list[str]:
    created_parents = _missing_ancestors(output.parent)
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        return _render_pack_stage(output, generated, manifest, previous_snapshot)
    except BaseException:
        _cleanup_created_ancestors(created_parents)
        raise


def _catalog(root_path: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    packs = load_yaml(root_path / "registry" / "packs.yaml").get("packs", [])
    capabilities = load_yaml(root_path / "registry" / "capabilities.yaml").get("capabilities", [])
    if not isinstance(packs, list) or not isinstance(capabilities, list):
        raise ValueError("pack and capability registries must contain lists")
    return packs, capabilities


def build_pack(root: Path | str, pack: dict[str, Any], output_root: Path | str) -> list[str]:
    root_path = Path(root).resolve()
    packs_path = root_path / "registry" / "packs.yaml"
    capabilities_path = root_path / "registry" / "capabilities.yaml"
    if not os.path.lexists(packs_path) and not os.path.lexists(capabilities_path):
        # Preserve direct-pack callers whose synthetic roots predate catalog registries.
        declared = pack.get("skills")
        standalone_skills = []
        if isinstance(declared, list):
            standalone_skills = list(dict.fromkeys(
                value for value in declared if isinstance(value, str)
            ))
        packs = [{**pack, "depends_on": []}]
        capabilities = [
            {"id": skill_name, "depends_on": []}
            for skill_name in standalone_skills
        ]
    else:
        packs, capabilities = _catalog(root_path)
        pack_id = _safe_component(pack.get("id"), "pack id")
        canonical_matches = [
            candidate
            for candidate in packs
            if isinstance(candidate, dict) and candidate.get("id") == pack_id
        ]
        if len(canonical_matches) == 1:
            canonical_pack = canonical_matches[0]
            if pack != canonical_pack:
                raise ValueError(
                    f"pack {pack_id} does not match canonical catalog record"
                )
            pack = canonical_pack
    return _publish_pack_plan(
        *_pack_plan(root_path, pack, output_root, packs=packs, capabilities=capabilities)
    )


def build_all_packs(root: Path | str, output_root: Path | str) -> dict[str, list[str]]:
    root_path = Path(root).resolve()
    packs, capabilities = _catalog(root_path)
    plans = [
        _pack_plan(root_path, pack, output_root, packs=packs, capabilities=capabilities)
        for pack in packs
    ]
    pack_ids = [str(plan[2]["pack"]) for plan in plans]
    if len(set(pack_ids)) != len(pack_ids):
        raise ValueError("pack registry contains duplicate pack ids")
    return {
        pack_id: _publish_pack_plan(*plan)
        for pack_id, plan in zip(pack_ids, plans)
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build deterministic skill packs.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--output", default="dist/packs")
    args = parser.parse_args(argv)
    report = build_all_packs(Path(args.root), Path(args.output))
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
