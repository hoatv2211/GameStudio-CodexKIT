GENERATED_HEADER = "Generated by scripts/project_scaffold.py. Do not edit manually."


DEFAULT_EXCLUDED_DIRECTORIES = {
    ".agents",
    ".archive",
    ".cache",
    ".git",
    "archive",
    "bin",
    "Library",
    "Logs",
    "node_modules",
    "obj",
    "Temp",
}


def _is_reparse_point(path: Path) -> bool:
    try:
        attributes = getattr(path.lstat(), "st_file_attributes", 0)
    except OSError:
        return True
    return path.is_symlink() or bool(attributes & 0x400)


def _walk(root: Path, exclusions: Iterable[str] = ()) -> Iterable[tuple[Path, tuple[str, ...], tuple[str, ...]]]:
    excluded = {name.casefold() for name in DEFAULT_EXCLUDED_DIRECTORIES}
    excluded.update(name.casefold() for name in exclusions)
    for current, directory_names, file_names in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        kept: list[str] = []
        for name in directory_names:
            candidate = current_path / name
            if name.casefold() in excluded or _is_reparse_point(candidate):
                continue
            kept.append(name)
        directory_names[:] = kept
        yield current_path, tuple(kept), tuple(file_names)


def _files(root: Path, exclusions: Iterable[str] = ()) -> Iterable[Path]:
    for current, _directory_names, file_names in _walk(root, exclusions):
        for name in file_names:
            yield current / name


def _valid_git_marker(repository: Path) -> bool:
    marker = repository / ".git"
    if marker.is_dir():
        return (marker / "HEAD").is_file()
    if not marker.is_file():
        return False
    try:
        first_line = marker.read_text(encoding="utf-8", errors="replace").splitlines()[0]
    except (OSError, IndexError):
        return False
    if not first_line.casefold().startswith("gitdir:"):
        return False
    target_text = first_line.split(":", 1)[1].strip()
    if not target_text:
        return False
    target = Path(target_text)
    if not target.is_absolute():
        target = repository / target
    return target.is_dir() and (target / "HEAD").is_file()


def detect_git_roots(root: Path | str, exclusions: Iterable[str] = ()) -> list[str]:
    root_path = Path(root).resolve()
    git_roots: list[str] = []
    excluded = {name.casefold() for name in DEFAULT_EXCLUDED_DIRECTORIES if name != ".git"}
    excluded.update(name.casefold() for name in exclusions)
    for current, directory_names, file_names in os.walk(root_path, topdown=True, followlinks=False):
        current_path = Path(current)
        if (".git" in directory_names or ".git" in file_names) and _valid_git_marker(current_path):
            relative = current_path.relative_to(root_path).as_posix()
            git_roots.append(relative if relative != "." else ".")
        kept: list[str] = []
        for name in directory_names:
            candidate = current_path / name
            if name == ".git" or name.casefold() in excluded or _is_reparse_point(candidate):
                continue
            kept.append(name)
        directory_names[:] = kept
    return sorted(set(git_roots))


def detect_subsystems(root: Path | str, exclusions: Iterable[str] = ()) -> set[str]:
    root_path = Path(root).resolve()
    subsystems: set[str] = set()
    for current, directory_names, file_names in _walk(root_path, exclusions):
        if "Assets" in directory_names and "ProjectSettings" in directory_names:
            subsystems.add("unity")
        for name in file_names:
            path = current / name
            suffix = path.suffix.casefold()
            if suffix in {".csproj", ".sln", ".vcxproj"} or name == "CMakeLists.txt":
                subsystems.add("server")
            if suffix == ".lua":
                subsystems.add("lua")
            if name in {"pom.xml", "build.gradle", "build.gradle.kts"} or suffix == ".gradle":
                subsystems.add("java")
            if suffix == ".sql" or "database" in {part.casefold() for part in path.parts}:
                subsystems.add("database")
    return subsystems


def draft_project_profile(root: Path | str) -> dict[str, object]:
    root_path = Path(root).resolve()
    git_roots = detect_git_roots(root_path)
    repository_paths = git_roots or ["."]
    repositories: list[dict[str, object]] = []
    for relative in repository_paths:
        repository_root = root_path if relative == "." else root_path / relative
        repository_id = "workspace" if relative == "." else relative.replace("/", "-").casefold()
        subsystems = sorted(detect_subsystems(repository_root)) or ["unclassified"]
        repositories.append(
            {
                "id": repository_id,
                "path": relative,
                "git_root": relative in git_roots,
                "subsystems": subsystems,
                "owner_skill": "studio-project-intake",
                "validation": [],
            }
        )
    return {
        "schema_version": 1,
        "workspace": {
            "name": root_path.name,
            "root_git": "." in git_roots,
            "default_concurrency": min(2, max(0, len(repositories) - 1)),
        },
        "repositories": repositories,
        "exclusions": sorted(
            name
            for name in DEFAULT_EXCLUDED_DIRECTORIES
            if name not in {".agents", ".git"}
        ),
        "agents": {"specialists": []},
        "cross_project_contracts": [],
    }


def _agent_entries(subsystems: list[str]) -> list[dict[str, str]]:
    entries = [{"id": "orchestrator", "scope": "shared governance and integration"}]
    entries.extend({"id": subsystem, "scope": f"{subsystem} subsystem"} for subsystem in subsystems)
    return entries


def _profile_subsystems(profile: dict[str, object]) -> list[str]:
    repositories = profile.get("repositories", [])
    return sorted(
        {
            subsystem
            for repository in repositories
            for subsystem in repository.get("subsystems", [])
            if subsystem != "unclassified"
        }
    )


def _profile_git_roots(profile: dict[str, object]) -> list[str]:
    return sorted(
        str(repository["path"])
        for repository in profile.get("repositories", [])
        if repository.get("git_root")
    )


def scaffold_files(
    root: Path | str,
    profile: dict[str, object] | None = None,
) -> dict[Path, str]:
    root_path = Path(root).resolve()
    profile = draft_project_profile(root_path) if profile is None else profile
    subsystems = _profile_subsystems(profile)
    subsystem_text = ", ".join(subsystems) if subsystems else "unclassified"
    skill_root = root_path / ".agents" / "skills"
    local_skills = sorted(
        directory.name
        for directory in skill_root.iterdir()
        if directory.is_dir() and (directory / "SKILL.md").is_file()
    ) if skill_root.exists() else []
    agents = f"""<!-- {GENERATED_HEADER} -->
# Project Agent Contract

- Detected subsystems: {subsystem_text}.
- Read-only inspection is the default.
- One writer owns each file or generated output.
- Preserve external, vendor, binary, generated, and credential paths.
- Use Verified, Snapshot, Unverified, and BLOCKED evidence labels.
- Do not commit, publish, start services, import databases, or perform destructive cleanup without explicit approval.
"""
    contract = f"""<!-- {GENERATED_HEADER} -->
# Agent Ownership Contract

The orchestrator owns shared governance and final verification. Subsystem agents own only exact declared paths. Reviewers are read-only. Generated files are changed through their source. External projects remain read-only unless separately authorized.
"""
    handoff = f"""<!-- {GENERATED_HEADER} -->
# HANDOFF

## Goal
Unverified.

## Scope Ownership and Do-Not-Touch
- Snapshot: detected subsystems are {subsystem_text}.

## Files Touched
None.

## Commands and Tests
None.

## Verified
None.

## Snapshot
Initial scaffold only.

## Unverified
Runtime topology, versions, ports, schemas, and owners require project intake.

## BLOCKED
Live verification has not run.

## Next Actions
1. Run project intake.
2. Verify subsystem owners.
3. Replace snapshot assumptions with commands.

## Reactivation Prompt
Inspect this repository read-only, verify the scaffold snapshot, and create a bounded task packet.
"""
    registry = {
        "_generated": GENERATED_HEADER,
        "schema_version": 1,
        "subsystems": subsystems,
        "agents": _agent_entries(subsystems),
        "skills": local_skills,
    }
    return {
        root_path / "AGENTS.md": agents,
        root_path / "HANDOFF.md": handoff,
        root_path / ".agents" / "CONTRACT.md": contract,
        root_path / ".agents" / "project-profile.yaml": yaml.safe_dump(
            profile, sort_keys=False
        ),
        root_path / ".agents" / "references" / "workspace-map.md": render_workspace_map(profile),
        root_path / ".agents" / "references" / "validation-matrix.md": render_validation_matrix(profile),
        root_path / ".agents" / "registry.json": json.dumps(registry, indent=2) + "\n",
    }


def _scaffold_operations(
    root: Path,
    profile: dict[str, object] | None = None,
) -> tuple[list[dict[str, str]], list[str], dict[str, object]]:
    project_profile = draft_project_profile(root) if profile is None else profile
    operations: list[dict[str, str]] = []
    preserved: list[str] = []
    for path, content in scaffold_files(root, project_profile).items():
        relative = path.relative_to(root).as_posix()
        if path.exists():
            preserved.append(relative)
            continue
        operations.append({"path": relative, "content": content})
    return operations, sorted(preserved), project_profile

def scaffold_project(root: Path | str) -> dict[str, object]:
    root_path = Path(root).resolve()
    operations, preserved, profile = _scaffold_operations(root_path)
    report = report_mutation(root_path, operations)
    return {
        "status": "REPORT_ONLY",
        "root": str(root_path),
        "proposed": sorted(operation["path"] for operation in operations),
        "preserved": preserved,
        "subsystems": _profile_subsystems(profile),
        "git_roots": _profile_git_roots(profile),
        "mutation_report": report,
    }


def apply_scaffold(
    root: Path | str,
    *,
    reviewer: str,
    backup_root: Path | str,
) -> dict[str, object]:
    if not reviewer.strip():
        raise ValueError("reviewer is required for scaffold apply")
    root_path = Path(root).resolve()
    operations, preserved, profile = _scaffold_operations(root_path)
    manifest_path = apply_mutation(root_path, operations, backup_root)
    restore_script = Path(__file__).resolve().with_name("safe_mutation.py")
    return {
        "status": "PASS",
        "root": str(root_path),
        "created": sorted(operation["path"] for operation in operations),
        "preserved": preserved,
        "subsystems": _profile_subsystems(profile),
        "git_roots": _profile_git_roots(profile),
        "reviewer": reviewer,
        "manifest": str(manifest_path),
        "restore_argv": [
            sys.executable,
            str(restore_script),
            "--mode",
            "restore",
            "--root",
            str(root_path),
            "--manifest",
            str(manifest_path),
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Bootstrap project-local game studio governance.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--reviewer")
    parser.add_argument("--backup-root")
    args = parser.parse_args(argv)
    if args.apply:
        if not args.reviewer or not args.backup_root:
            parser.error("--apply requires --reviewer and --backup-root")
        report = apply_scaffold(
            Path(args.root),
            reviewer=args.reviewer,
            backup_root=Path(args.backup_root),
        )
    else:
        report = scaffold_project(Path(args.root))
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
