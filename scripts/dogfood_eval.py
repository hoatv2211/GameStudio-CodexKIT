from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path
from typing import Any


DEFAULT_CASES = Path("evals/dogfood/game-studio-scenarios.json")
GENERATED_MARKER = "Generated by scripts/dogfood_eval.py. Do not edit manually."
EVIDENCE_LABELS = {"Verified", "Snapshot", "Unverified", "BLOCKED"}


def load_cases(root: Path | str) -> list[dict[str, Any]]:
    path = Path(root).resolve() / DEFAULT_CASES
    payload = json.loads(path.read_text(encoding="utf-8"))
    if (
        not isinstance(payload, dict)
        or payload.get("schema_version") != 1
        or not isinstance(payload.get("cases"), list)
    ):
        raise ValueError("dogfood fixture must contain schema_version 1 and a cases list")
    cases = payload["cases"]
    required_fields = ("id", "workflow", "project_kind", "prompt", "required_artifacts", "allow_mutation")
    ids: list[str] = []
    for index, case in enumerate(cases):
        if not isinstance(case, dict) or any(field not in case for field in required_fields):
            raise ValueError(f"dogfood case {index} is missing required fields")
        if any(not isinstance(case[field], str) or not case[field].strip() for field in required_fields[:4]):
            raise ValueError(f"dogfood case {case['id']!r} has invalid text fields")
        artifacts = case["required_artifacts"]
        if (
            not isinstance(artifacts, list)
            or not artifacts
            or not all(isinstance(item, str) and item.strip() for item in artifacts)
            or len(set(artifacts)) != len(artifacts)
        ):
            raise ValueError(f"dogfood case {case['id']!r} has invalid required_artifacts")
        if not isinstance(case["allow_mutation"], bool):
            raise ValueError(f"dogfood case {case['id']!r} has invalid allow_mutation")
        ids.append(case["id"])
    if len(set(ids)) != len(ids):
        raise ValueError("dogfood case ids must be unique")
    return cases


def export_cases(root: Path | str, output: Path | str) -> int:
    rows: list[dict[str, Any]] = []
    for case in load_cases(root):
        row = dict(case)
        row["runner_contract"] = (
            "Run only the named workflow against the supplied real project snapshot. "
            "Return one result with command, exit_code, evidence_label, artifact paths, "
            "project_snapshot, reviewer, restore information, and mutation declaration."
        )
        rows.append(row)
    output_path = Path(output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "".join(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n" for row in rows),
        encoding="utf-8",
    )
    return len(rows)


def write_blocked_status(path: Path | str, reason: str) -> Path:
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "_generated": GENERATED_MARKER,
        "verdict": "BLOCKED",
        "kind": "dogfood",
        "reason": reason,
        "runner": "Hermes",
        "observed_cases": 0,
        "passed": 0,
        "pass_rate": None,
        "unique_ids": 0,
        "covered_workflows": [],
    }
    output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return output


def _iso_timestamp(value: Any) -> bool:
    try:
        dt.datetime.fromisoformat(str(value))
    except ValueError:
        return False
    return True


def _artifact_kinds(value: Any) -> set[str]:
    if not isinstance(value, list):
        return set()
    return {
        str(item.get("kind"))
        for item in value
        if isinstance(item, dict) and isinstance(item.get("kind"), str) and item.get("path")
    }


def _validate_pass(case: dict[str, Any], result: dict[str, Any]) -> list[str]:
    failures: list[str] = []
    if result.get("evidence_label") != "Verified":
        failures.append("PASS requires evidence_label Verified")
    if result.get("exit_code") != 0:
        failures.append("PASS requires exit_code 0")
    if not isinstance(result.get("command"), str) or not result["command"].strip():
        failures.append("command is required")
    if not isinstance(result.get("project_snapshot"), str) or not result["project_snapshot"].strip():
        failures.append("project_snapshot is required")
    if not isinstance(result.get("reviewer"), str) or not result["reviewer"].strip():
        failures.append("reviewer is required")
    if not _iso_timestamp(result.get("timestamp")):
        failures.append("timestamp must be ISO-8601")
    if result.get("unauthorized_write") is not False:
        failures.append("unauthorized_write must be false")
    if not isinstance(result.get("restore"), str) or not result["restore"].strip():
        failures.append("restore information is required")
    missing = sorted(set(case["required_artifacts"]) - _artifact_kinds(result.get("artifacts")))
    if missing:
        failures.append(f"missing required artifact kinds: {missing}")
    return failures


def evaluate_results(root: Path | str, results_path: Path | str | None) -> dict[str, Any]:
    cases = load_cases(root)
    expected = {case["id"]: case for case in cases}
    if results_path is None or not Path(results_path).exists():
        return {
            "verdict": "BLOCKED",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": [],
            "blocked": ["No governed game-project dogfood results were supplied"],
        }
    try:
        results = json.loads(Path(results_path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return {
            "verdict": "FAIL",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": [str(error)],
            "blocked": [],
        }
    if not isinstance(results, list):
        return {
            "verdict": "FAIL",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": ["results must be a JSON array"],
            "blocked": [],
        }

    by_id: dict[str, dict[str, Any]] = {}
    failures: list[str] = []
    blocked: list[str] = []
    for result in results:
        if not isinstance(result, dict) or not isinstance(result.get("id"), str):
            failures.append("every result requires a string id")
            continue
        result_id = result["id"]
        if result_id in by_id:
            failures.append(f"duplicate result id: {result_id}")
            continue
        by_id[result_id] = result
    missing = sorted(set(expected) - set(by_id))
    extra = sorted(set(by_id) - set(expected))
    failures.extend(f"missing result: {item}" for item in missing)
    failures.extend(f"unknown result: {item}" for item in extra)
    passed = 0
    for result_id, case in expected.items():
        result = by_id.get(result_id)
        if result is None:
            continue
        if result.get("workflow") != case["workflow"]:
            failures.append(f"{result_id}: workflow does not match case")
        verdict = result.get("verdict")
        if verdict == "PASS":
            case_failures = _validate_pass(case, result)
            failures.extend(f"{result_id}: {reason}" for reason in case_failures)
            if not case_failures:
                passed += 1
        elif verdict == "BLOCKED":
            if result.get("evidence_label") != "BLOCKED" or not result.get("reason"):
                failures.append(f"{result_id}: BLOCKED requires evidence_label and reason")
            else:
                blocked.append(result_id)
        elif verdict == "FAIL":
            if result.get("evidence_label") not in EVIDENCE_LABELS or not result.get("reason"):
                failures.append(f"{result_id}: FAIL requires evidence_label and reason")
        else:
            failures.append(f"{result_id}: verdict must be PASS, FAIL, or BLOCKED")
    if failures:
        verdict = "FAIL"
    elif blocked:
        verdict = "BLOCKED"
    else:
        verdict = "PASS"
    return {
        "verdict": verdict,
        "total_cases": len(cases),
        "observed_cases": len(by_id),
        "passed": passed,
        "unique_ids": len(by_id),
        "failures": failures,
        "blocked": blocked,
    }


def write_summaries(root: Path | str, results_path: Path | str, output_root: Path | str) -> list[Path]:
    report = evaluate_results(root, results_path)
    if report["verdict"] != "PASS":
        raise ValueError("dogfood summaries require a complete PASS result set")
    results = {item["id"]: item for item in json.loads(Path(results_path).read_text(encoding="utf-8"))}
    written: list[Path] = []
    output_path = Path(output_root)
    for case in load_cases(root):
        result = results[case["id"]]
        summary_path = output_path / case["id"] / "dogfood-summary.json"
        summary_path.parent.mkdir(parents=True, exist_ok=True)
        summary_path.write_text(
            json.dumps(
                {
                    "_generated": GENERATED_MARKER,
                    "label": "Verified",
                    "workflow": case["workflow"],
                    "case_id": case["id"],
                    "exit_code": 0,
                    "command": result["command"],
                    "artifacts": result["artifacts"],
                    "project_snapshot": result["project_snapshot"],
                    "reviewer": result["reviewer"],
                    "timestamp": result["timestamp"],
                    "unauthorized_write": False,
                    "restore": result["restore"],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        written.append(summary_path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export and validate governed real-project dogfood scenarios.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--export", type=Path)
    parser.add_argument("--results", type=Path)
    parser.add_argument("--status", type=Path)
    parser.add_argument("--summary-dir", type=Path)
    args = parser.parse_args(argv)
    if args.summary_dir and not args.results:
        parser.error("--summary-dir requires --results")
    if args.export:
        print(f"dogfood-export: {export_cases(args.root, args.export)} cases")
    if args.status:
        write_blocked_status(args.status, "No governed Hermes runner and real game-project snapshot were supplied")
        print(args.status)
    if args.results:
        report = evaluate_results(args.root, args.results)
        print(json.dumps(report, indent=2))
        if report["verdict"] == "PASS" and args.summary_dir:
            written = write_summaries(args.root, args.results, args.summary_dir)
            print(f"dogfood-summaries: {len(written)} written to {args.summary_dir}")
        return 0 if report["verdict"] == "PASS" else 2 if report["verdict"] == "BLOCKED" else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
