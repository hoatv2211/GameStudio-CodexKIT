def _normalized_owned_files(
    project: Path,
    adapter: dict[str, Any],
) -> list[tuple[dict[str, str], Path]] | None:
    files = adapter.get("files")
    if not isinstance(files, list):
        return None
    normalized_files: list[tuple[dict[str, str], Path]] = []
    seen_destinations: set[str] = set()
    for owned in files:
        if not isinstance(owned, dict):
            return None
        relative = owned.get("path")
        sha256 = owned.get("sha256")
        if not isinstance(relative, str) or not relative:
            return None
        if (
            not isinstance(sha256, str)
            or len(sha256) != 64
            or any(character not in "0123456789abcdefABCDEF" for character in sha256)
        ):
            return None
        try:
            normalized, candidate = _manifest_owned_project_path(project, relative)
        except ValueError:
            return None
        destination_identity = _owned_destination_identity(candidate)
        if destination_identity in seen_destinations:
            return None
        seen_destinations.add(destination_identity)
        normalized_files.append(
            ({"path": normalized, "sha256": sha256.lower()}, candidate)
        )
    return normalized_files
