MARKER = "Generated by scripts/generate_adapters.py. Do not edit manually."

class _UninstallReport(dict[str, object]):
    def __contains__(self, item: object) -> bool:
        if super().__contains__(item):
            return True
        if not isinstance(item, str):
            return False
        prefix = f".agents/skills/{item}/"
        removed = self.get("removed", [])
        remaining = [
            *self.get("remaining_owned", []),
            *self.get("recovery_owned", []),
        ]
        removed_path = any(
            isinstance(path, str) and path.startswith(prefix)
            for path in removed
        )
        remaining_path = any(
            isinstance(owned, dict)
            and isinstance(owned.get("path"), str)
            and owned["path"].startswith(prefix)
            for owned in remaining
        )
        return removed_path and not remaining_path

def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _is_reparse_point(path: Path) -> bool:
    try:
        info = path.lstat()
    except FileNotFoundError:
        return False
    attributes = getattr(info, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return path.is_symlink() or bool(attributes & reparse_flag)


def _safe_project_path(
    project: Path,
    relative: str,
    *,
    required_prefix: tuple[str, ...],
) -> Path:
    normalized = relative.replace("\\", "/")
    pure = PurePosixPath(normalized)
    parts = pure.parts
    if pure.is_absolute() or not parts or ".." in parts or "." in parts:
        raise ValueError(f"unsafe project adapter path: {relative}")
    if parts[: len(required_prefix)] != required_prefix:
        raise ValueError(f"project adapter path is outside its owned scope: {relative}")

    project_root = project.resolve()
    candidate = project_root.joinpath(*parts)
    current = project_root
    if _is_reparse_point(current):
        raise ValueError(f"project root is a symlink or reparse point: {current}")
    for part in parts:
        current = current / part
        if _is_reparse_point(current):
            raise ValueError(f"symlink or reparse point is not allowed: {current}")

    owned_root = project_root.joinpath(*required_prefix).resolve()
    resolved = candidate.resolve()
    try:
        resolved.relative_to(owned_root)
    except ValueError as error:
        raise ValueError(f"project adapter path escapes its owned scope: {relative}") from error
    return candidate


def _has_generated_header(text: str) -> bool:
    lines = text.splitlines()
    return bool(lines) and lines[0] in {f"# {MARKER}", f"<!-- {MARKER} -->"}

def _generated_skill(text: str) -> str:
    return f"# {MARKER}\n{text}"


def _generated_resource(source: Path) -> str:
    text = source.read_text(encoding="utf-8")
    if source.name == "SKILL.md":
        return _generated_skill(text)
    if source.suffix.casefold() in {".py", ".sh", ".ps1", ".yaml", ".yml", ".toml"}:
        return f"# {MARKER}\n\n{text}"
    if source.suffix.casefold() in {".md", ".txt"}:
        return f"<!-- {MARKER} -->\n{text}"
    raise ValueError(f"unsupported skill resource type: {source}")


def _skill_files(skill_file: Path) -> list[Path]:
    return sorted(path for path in skill_file.parent.rglob("*") if path.is_file())


def _capabilities(root: Path) -> list[dict[str, Any]]:
    registry = load_yaml(root / "registry" / "capabilities.yaml")
    return registry.get("capabilities", [])


def _prepare_managed_output(output: Path) -> None:
    if not output.exists():
        return
    for file in (item for item in output.rglob("*") if item.is_file()):
        text = file.read_text(encoding="utf-8", errors="replace")
        if file.name == "registry.json":
            try:
                managed = json.loads(text).get("_generated") == MARKER
            except (AttributeError, json.JSONDecodeError):
                managed = False
        else:
            managed = _has_generated_header(text)
        if not managed:
            raise RuntimeError(f"refusing to replace unmanaged adapter file: {file}")
    shutil.rmtree(output)


def _write_standard_adapter(root: Path, target: str, output: Path) -> dict[str, object]:
    _prepare_managed_output(output)
    created: list[str] = []
    capabilities = _capabilities(root)
    for capability in capabilities:
        skill_file = root / capability["path"]
        for source in _skill_files(skill_file):
            relative_resource = source.relative_to(skill_file.parent)
            destination = output / "skills" / capability["id"] / relative_resource
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(_generated_resource(source), encoding="utf-8", newline="\n")
            created.append(destination.relative_to(output).as_posix())
    registry = {
        "_generated": MARKER,
        "schema_version": 1,
        "target": target,
        "skills": [capability["id"] for capability in capabilities],
    }
    (output / "registry.json").write_text(json.dumps(registry, indent=2) + "\n", encoding="utf-8")
    created.append("registry.json")
    return {"target": target, "created": sorted(created), "preserved": []}


def _read_project_registry(project: Path) -> dict[str, Any]:
    path = _safe_project_path(
        project,
        ".agents/registry.json",
        required_prefix=(".agents",),
    )
    if not path.exists():
        return {"schema_version": 1, "skills": []}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("project .agents/registry.json must be an object")
    return data


def _owned_project_path(project: Path, relative: str) -> tuple[str, Path]:
    normalized = PurePosixPath(relative.replace("\\", "/")).as_posix()
    parts = PurePosixPath(normalized).parts
    if len(parts) >= 4 and parts[:2] == (".agents", "skills"):
        required_prefix = (".agents", "skills", parts[2])
    elif len(parts) == 3 and parts[:2] == (".codex", "agents"):
        required_prefix = (".codex", "agents")
    elif parts == (".codex", "agents.generated.toml"):
        required_prefix = (".codex",)
    else:
        raise ValueError(f"unsupported project adapter owned path: {relative}")
    return normalized, _safe_project_path(
        project,
        normalized,
        required_prefix=required_prefix,
    )

def _manifest_owned_project_path(project: Path, relative: str) -> tuple[str, Path]:
    normalized = PurePosixPath(relative.replace("\\", "/")).as_posix()
    parts = PurePosixPath(normalized).parts
    if len(parts) >= 4 and parts[:2] == (".agents", "skills"):
        required_prefix = (".agents", "skills", parts[2])
    elif len(parts) == 3 and parts[:2] == (".codex", "agents"):
        required_prefix = (".codex", "agents")
    elif parts == (".codex", "agents.generated.toml"):
        required_prefix = (".codex",)
    else:
        raise ValueError(f"unsupported project adapter owned path: {relative}")
    parent_relative = PurePosixPath(*parts[:-1]).as_posix()
    parent = _safe_project_path(
        project,
        parent_relative,
        required_prefix=required_prefix,
    )
    return normalized, parent / parts[-1]

def _owned_destination_identity(candidate: Path) -> str:
    parent = candidate.parent.resolve()
    return os.path.normcase(os.path.abspath(str(parent / candidate.name)))

def _project_adapter_plan(root: Path, project: Path) -> dict[str, object]:
    capabilities = _capabilities(root)
    overlay_plan = plan_agent_overlay(
        project,
        template_root=(
            root / "skills" / "studio-project-scaffold" / "templates" / "agents"
        ),
        profile_path=project / ".agents" / "project-profile.yaml",
        known_skills={str(capability["id"]) for capability in capabilities},
    )

    registry = _read_project_registry(project)
    previous_owned: dict[str, dict[str, str]] = {}
    previous_adapter = registry.get("kit_adapter", {})
    if previous_adapter.get("adapter_id") in {
        "GameStudio-CodexKIT/per-project/v1",
        "GameStudio-CodexKIT/per-project/v2",
    }:
        for owned in previous_adapter.get("files", []):
            if not isinstance(owned, dict):
                continue
            try:
                normalized, candidate = _owned_project_path(
                    project,
                    str(owned.get("path", "")),
                )
            except ValueError:
                continue
            if candidate.exists():
                previous_owned[normalized] = {
                    "path": normalized,
                    "sha256": str(owned.get("sha256", "")),
                }

    operations: list[dict[str, str]] = []
    preserved: list[str] = []
    owned_by_path = dict(previous_owned)
    skill_root = _safe_project_path(
        project,
        ".agents/skills",
        required_prefix=(".agents", "skills"),
    )
    planned_skill_names: set[str] = set()
    for capability in capabilities:
        capability_id = str(capability["id"])
        skill_file = root / capability["path"]
        for source in _skill_files(skill_file):
            relative_resource = source.relative_to(skill_file.parent)
            relative = PurePosixPath(
                ".agents",
                "skills",
                capability_id,
                *relative_resource.parts,
            ).as_posix()
            destination = _safe_project_path(
                project,
                relative,
                required_prefix=(".agents", "skills", capability_id),
            )
            if destination.exists() and not destination.is_file():
                preserved.append(destination.relative_to(project).as_posix())
                continue
            existing_text = (
                destination.read_text(encoding="utf-8", errors="replace")
                if destination.is_file()
                else ""
            )
            previous = previous_owned.get(relative)
            previous_hash_matches = (
                previous is not None
                and destination.is_file()
                and hashlib.sha256(destination.read_bytes()).hexdigest() == previous["sha256"]
            )
            if destination.exists() and not (
                _has_generated_header(existing_text) or previous_hash_matches
            ):
                preserved.append(destination.relative_to(project).as_posix())
                continue
            generated_text = _generated_resource(source)
            operations.append({"path": relative, "content": generated_text})
            owned_by_path[relative] = {
                "path": relative,
                "sha256": _sha256_text(generated_text),
            }
        planned_skill_names.add(capability_id)

    for operation in overlay_plan["operations"]:
        relative = str(operation["path"])
        normalized, _destination = _owned_project_path(project, relative)
        content = str(operation["content"])
        operations.append({"path": normalized, "content": content})
        owned_by_path[normalized] = {
            "path": normalized,
            "sha256": _sha256_text(content),
        }
    preserved.extend(str(path) for path in overlay_plan["preserved"])

    if skill_root.exists():
        planned_skill_names.update(
            directory.name
            for directory in skill_root.iterdir()
            if directory.is_dir() and (directory / "SKILL.md").exists()
        )
    registry["schema_version"] = registry.get("schema_version", 1)
    registry["skills"] = sorted(planned_skill_names)
    registry["kit_adapter"] = {
        "_generated": MARKER,
        "adapter_id": "GameStudio-CodexKIT/per-project/v2",
        "source": "GameStudio-CodexKIT",
        "target": "per-project",
        "files": sorted(owned_by_path.values(), key=lambda item: item["path"]),
    }
    registry_relative = ".agents/registry.json"
    _safe_project_path(project, registry_relative, required_prefix=(".agents",))
    operations.append(
        {
            "path": registry_relative,
            "content": json.dumps(registry, indent=2) + "\n",
        }
    )
    if any(operation["path"] == ".codex/config.toml" for operation in operations):
        raise RuntimeError("project adapter must never mutate .codex/config.toml")
    return {
        "target": "per-project",
        "operations": operations,
        "preserved": sorted(set(preserved)),
        "collisions": sorted(
            overlay_plan["collisions"],
            key=lambda collision: str(collision["path"]),
        ),
        "activated_roles": list(overlay_plan["activated_roles"]),
    }
def _plan_digest(mutation_report: dict[str, Any]) -> str:
    normalized_operations = sorted(
        (
            {
                "path": str(operation["path"]).replace("\\", "/"),
                "action": operation["action"],
                "before_sha256": operation["before_sha256"],
                "after_sha256": operation["after_sha256"],
            }
            for operation in mutation_report["operations"]
        ),
        key=lambda operation: operation["path"],
    )
    payload = {
        "root": str(Path(mutation_report["root"]).resolve()),
        "operations": normalized_operations,
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _validated_backup_root(
    project: Path,
    backup_root: Path | str,
    operations: list[dict[str, str]],
) -> Path:
    project_root = project.resolve()
    backup_path = Path(backup_root).resolve()
    try:
        relative_backup = backup_path.relative_to(project_root)
    except ValueError as error:
        raise ValueError("backup root must remain inside the project root") from error
    current = project_root
    if _is_reparse_point(current):
        raise ValueError(f"project root is a symlink or reparse point: {current}")
    for part in relative_backup.parts:
        current = current / part
        if current.exists() and _is_reparse_point(current):
            raise ValueError(f"symlink or reparse point is not allowed: {current}")
    for operation in operations:
        relative = PurePosixPath(str(operation["path"]).replace("\\", "/"))
        target = project_root.joinpath(*relative.parts).resolve()
        if (
            backup_path == target
            or target.is_relative_to(backup_path)
            or backup_path.is_relative_to(target)
        ):
            raise ValueError(
                f"backup root overlaps planned target {operation['path']}: {backup_path}"
            )
    return backup_path


def report_project_adapter(root: Path | str, project: Path | str) -> dict[str, object]:
    root_path = Path(root).resolve()
    project_path = Path(project).resolve()
    plan = _project_adapter_plan(root_path, project_path)
    operations = list(plan["operations"])
    mutation_report = report_mutation(project_path, operations)
    plan_digest = _plan_digest(mutation_report)
    created = sorted(
        item["path"] for item in mutation_report["operations"] if item["action"] == "create"
    )
    updated = sorted(
        item["path"] for item in mutation_report["operations"] if item["action"] == "update"
    )
    return {
        "status": "REPORT_ONLY",
        "target": "per-project",
        "root": str(project_path),
        "plan_digest": plan_digest,
        "proposed": sorted(item["path"] for item in operations),
        "created": created,
        "updated": updated,
        "preserved": plan["preserved"],
        "collisions": plan["collisions"],
        "activated_roles": plan["activated_roles"],
        "mutation_report": mutation_report,
    }


def apply_project_adapter(
    root: Path | str,
    project: Path | str,
    *,
    reviewer: str,
    backup_root: Path | str,
    approved_plan_digest: str,
) -> dict[str, object]:
    reviewer_name = reviewer.strip()
    if not reviewer_name:
        raise ValueError("reviewer is required for project adapter apply")
    approved_digest = approved_plan_digest.strip()
    if not approved_digest:
        raise ValueError("approved_plan_digest is required for project adapter apply")
    root_path = Path(root).resolve()
    project_path = Path(project).resolve()
    plan = _project_adapter_plan(root_path, project_path)
    operations = list(plan["operations"])
    mutation_report = report_mutation(project_path, operations)
    current_plan_digest = _plan_digest(mutation_report)
    if current_plan_digest != approved_digest:
        raise ValueError(
            "project adapter plan changed since report; review the new report and approve its plan digest"
        )
    backup_path = _validated_backup_root(project_path, backup_root, operations)
    manifest_path = apply_mutation(
        project_path,
        operations,
        backup_path,
        expected_operations=mutation_report["operations"],
    )
    created = sorted(
        item["path"] for item in mutation_report["operations"] if item["action"] == "create"
    )
    updated = sorted(
        item["path"] for item in mutation_report["operations"] if item["action"] == "update"
    )
    restore_argv = [
        sys.executable,
        "-B",
        str(Path(__file__).resolve().with_name("safe_mutation.py")),
        "--root",
        str(project_path),
        "--mode",
        "restore",
        "--manifest",
        str(manifest_path),
    ]
    return {
        "status": "PASS",
        "target": "per-project",
        "root": str(project_path),
        "reviewer": reviewer_name,
        "plan_digest": current_plan_digest,
        "manifest": str(manifest_path),
        "restore_argv": restore_argv,
        "created": created,
        "updated": updated,
        "preserved": plan["preserved"],
        "collisions": plan["collisions"],
        "activated_roles": plan["activated_roles"],
    }

def generate_adapter(root: Path | str, target: str, output: Path | str) -> dict[str, object]:
    root_path = Path(root).resolve()
    output_path = Path(output).resolve()
    if target in {"hermes", "codex"}:
        return _write_standard_adapter(root_path, target, output_path)
    if target == "per-project":
        return report_project_adapter(root_path, output_path)
    raise ValueError(f"unsupported adapter target: {target}")

def _remaining_manifest_files(adapter: object) -> list[object]:
    if not isinstance(adapter, dict):
        return []
    files = adapter.get("files", [])
    return list(files) if isinstance(files, list) else []

