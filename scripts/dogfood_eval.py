def _validate_case_list(cases: object, *, label: str) -> list[dict[str, Any]]:
    if not isinstance(cases, list):
        raise ValueError(f"{label} must contain a cases list")
    required_fields = ("id", "workflow", "project_kind", "prompt", "required_artifacts", "allow_mutation")
    ids: list[str] = []
    normalized: list[dict[str, Any]] = []
    for index, case in enumerate(cases):
        if not isinstance(case, dict) or any(field not in case for field in required_fields):
            raise ValueError(f"{label} case {index} is missing required fields")
        if any(not isinstance(case[field], str) or not case[field].strip() for field in required_fields[:4]):
            raise ValueError(f"{label} case {case['id']!r} has invalid text fields")
        artifacts = case["required_artifacts"]
        if (
            not isinstance(artifacts, list)
            or not artifacts
            or not all(isinstance(item, str) and item.strip() for item in artifacts)
            or len(set(artifacts)) != len(artifacts)
        ):
            raise ValueError(f"{label} case {case['id']!r} has invalid required_artifacts")
        if not isinstance(case["allow_mutation"], bool):
            raise ValueError(f"{label} case {case['id']!r} has invalid allow_mutation")
        ids.append(case["id"])
        normalized.append(dict(case))
    if len(set(ids)) != len(ids):
        raise ValueError(f"{label} case ids must be unique")
    return normalized


def load_profile(root: Path | str, profile_id: str) -> dict[str, Any]:
    root_path = Path(root).resolve()
    profile_path = root_path / PROFILE_DIR / f"{profile_id}.json"
    if not profile_path.is_file():
        raise ValueError(f"unknown dogfood profile: {profile_id}")
    try:
        profile = json.loads(profile_path.read_text(encoding="utf-8"))
        schema = json.loads((root_path / PROFILE_SCHEMA).read_text(encoding="utf-8"))
        jsonschema.validate(profile, schema)
    except (OSError, json.JSONDecodeError, jsonschema.ValidationError) as error:
        raise ValueError(f"invalid dogfood profile {profile_id}: {error}") from error
    if profile.get("id") != profile_id:
        raise ValueError(f"dogfood profile id does not match filename: {profile_id}")
    cases = _validate_case_list(profile.get("cases"), label=f"profile {profile_id}")
    case_ids = [case["id"] for case in cases]
    if profile.get("case_ids") != case_ids:
        raise ValueError(f"profile {profile_id} case_ids must match cases")
    return profile


def load_cases(root: Path | str, *, profile: str | None = None) -> list[dict[str, Any]]:
    path = Path(root).resolve() / DEFAULT_CASES
    payload = json.loads(path.read_text(encoding="utf-8"))
    if (
        not isinstance(payload, dict)
        or payload.get("schema_version") != 1
        or not isinstance(payload.get("cases"), list)
    ):
        raise ValueError("dogfood fixture must contain schema_version 1 and a cases list")
    cases = _validate_case_list(payload["cases"], label="dogfood fixture")
    if profile is None:
        return cases
    selected = load_profile(root, profile)
    universal_ids = {case["id"] for case in cases}
    overlap = universal_ids.intersection(selected["case_ids"])
    if overlap:
        raise ValueError(f"profile {profile} reuses universal case ids: {sorted(overlap)}")
    return selected["cases"]


def export_cases(root: Path | str, output: Path | str, *, profile: str | None = None) -> int:
    rows: list[dict[str, Any]] = []
    for case in load_cases(root, profile=profile):
        row = dict(case)
        row["runner_contract"] = (
            "Run only the named workflow against the supplied real project snapshot. "
            "Return one strict result with command, exit_code, evidence_label, hashed artifact paths, "
            "project_snapshot, reviewer, restore information, and mutation declaration."
        )
        rows.append(row)
    output_path = Path(output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "".join(json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n" for row in rows),
        encoding="utf-8",
    )
    return len(rows)


