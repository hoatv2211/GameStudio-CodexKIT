def _regular_file_sha256(candidate: Path) -> str | None:
    try:
        info = candidate.lstat()
    except (FileNotFoundError, OSError):
        return None
    if _is_reparse_point(candidate) or not stat.S_ISREG(info.st_mode):
        return None
    try:
        return hashlib.sha256(candidate.read_bytes()).hexdigest()
    except OSError:
        return None

def _owned_regular_file_matches(candidate: Path, expected_sha256: str) -> bool:
    return _regular_file_sha256(candidate) == expected_sha256

