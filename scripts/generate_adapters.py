def _restore_quarantined(
    quarantined: list[tuple[dict[str, str], Path, Path]],
    preserved_drift: set[str],
) -> bool:
    restored = True
    for owned, candidate, quarantine_path in reversed(quarantined):
        if not os.path.lexists(quarantine_path):
            if not os.path.lexists(candidate):
                preserved_drift.add(owned["path"])
                restored = False
            continue
        if os.path.lexists(candidate):
            preserved_drift.add(owned["path"])
            if not _owned_regular_file_matches(quarantine_path, owned["sha256"]):
                restored = False
                continue
            try:
                quarantine_path.unlink()
            except OSError:
                restored = False
                continue
            if os.path.lexists(quarantine_path):
                restored = False
            continue
        if not _owned_regular_file_matches(quarantine_path, owned["sha256"]):
            preserved_drift.add(owned["path"])
        try:
            os.link(quarantine_path, candidate, follow_symlinks=False)
            os.unlink(quarantine_path)
        except OSError:
            preserved_drift.add(owned["path"])
            restored = False
    return restored

def _refresh_restored_recovery_records(
    recovery: dict[str, object] | None,
    quarantined: list[tuple[dict[str, str], Path, Path]],
) -> None:
    if recovery is None:
        return
    files = recovery.get("files")
    if not isinstance(files, list) or len(files) != len(quarantined):
        return
    recovery["state"] = "prepared"
    for record, (owned, candidate, quarantine_path) in zip(files, quarantined):
        if not isinstance(record, dict):
            continue
        record.pop("observed_sha256", None)
        if _owned_regular_file_matches(quarantine_path, owned["sha256"]):
            record["state"] = "moved"
            record["artifact_present"] = True
        elif _owned_regular_file_matches(candidate, owned["sha256"]):
            record["state"] = "source"
            record["artifact_present"] = False
        else:
            record["state"] = "missing"
            record["artifact_present"] = False

