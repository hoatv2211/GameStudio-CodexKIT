def _parse_timestamp(value: Any) -> dt.datetime | None:
    if not isinstance(value, str) or not value.strip():
        return None
    try:
        parsed = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        return None
    return parsed


def _normalized_unity_mcp_tool(value: str) -> str:
    if value.startswith(UNITY_MCP_TOOL_PREFIX):
        return value[len(UNITY_MCP_TOOL_PREFIX) :]
    return value


def _timestamp_failures(
    value: Any,
    *,
    label: str,
    now: dt.datetime,
    max_evidence_age_days: int,
) -> list[str]:
    parsed = _parse_timestamp(value)
    if parsed is None:
        return [f"{label} must be timezone-aware ISO-8601"]
    observed = parsed.astimezone(dt.timezone.utc)
    current = now.astimezone(dt.timezone.utc)
    if observed > current:
        return [f"{label} is in the future"]
    if observed < current - dt.timedelta(days=max_evidence_age_days):
        return [f"{label} is stale (older than {max_evidence_age_days} days)"]
    return []


def _is_placeholder(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    normalized = value.strip().casefold()
    return (
        not normalized
        or normalized in PLACEHOLDERS
        or normalized.startswith("todo:")
        or normalized.startswith("tbd:")
        or (normalized.startswith("<") and normalized.endswith(">"))
    )


def _sha256_path(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _normalized_legacy_result(value: Any) -> Any:
    if not isinstance(value, dict):
        return value
    result = dict(value)
    defaults = {
        "runtime_target": None,
        "command": None,
        "exit_code": None,
        "artifacts": [],
        "project_snapshot": None,
        "reviewer": None,
        "timestamp": None,
        "unauthorized_write": None,
        "restore": None,
        "reason": None,
    }
    for field, default in defaults.items():
        result.setdefault(field, default)
    return result


def _load_results(
    root: Path,
    results_path: Path,
) -> tuple[list[dict[str, Any]], bool, list[str]]:
    raw = json.loads(results_path.read_text(encoding="utf-8"))
    legacy = isinstance(raw, list)
    payload = (
        {"results": [_normalized_legacy_result(item) for item in raw]}
        if legacy
        else raw
    )
    schema = json.loads((root / RESULT_SCHEMA).read_text(encoding="utf-8"))
    validator = jsonschema.Draft202012Validator(schema)
    errors = sorted(validator.iter_errors(payload), key=lambda error: list(error.absolute_path))
    failures = []
    for error in errors:
        location = "/".join(str(item) for item in error.absolute_path) or "<root>"
        failures.append(f"result schema {location}: {error.message}")
    if failures or not isinstance(payload, dict) or not isinstance(payload.get("results"), list):
        return [], legacy, failures or ["result schema requires a results array"]
    return payload["results"], legacy, []


def _resolve_artifact(root: Path, value: object) -> Path:
    if not isinstance(value, str) or not value.strip():
        raise ValueError("artifact path must be a non-empty string")
    normalized = value.replace("\\", "/")
    pure = PurePosixPath(normalized)
    windows = PureWindowsPath(value)
    if (
        pure.is_absolute()
        or windows.is_absolute()
        or windows.drive
        or not pure.parts
        or "." in pure.parts
        or ".." in pure.parts
    ):
        raise ValueError(f"unsafe artifact path: {value}")
    target = root.joinpath(*pure.parts).resolve()
    try:
        target.relative_to(root)
    except ValueError as error:
        raise ValueError(f"artifact path escapes approved root: {value}") from error
    if not target.is_file():
        raise ValueError(f"artifact file does not exist: {value}")
    return target


def _normalized_artifact_path(value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError("artifact path must be a non-empty string")
    normalized = value.replace("\\", "/")
    pure = PurePosixPath(normalized)
    windows = PureWindowsPath(value)
    if (
        pure.is_absolute()
        or windows.is_absolute()
        or windows.drive
        or not pure.parts
        or "." in pure.parts
        or ".." in pure.parts
    ):
        raise ValueError(f"unsafe artifact path: {value}")
    return pure.as_posix().casefold()


def _json_object(path: Path, *, label: str) -> tuple[dict[str, Any] | None, list[str]]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        return None, [f"{label} must be a UTF-8 JSON object: {error}"]
    if not isinstance(payload, dict):
        return None, [f"{label} must be a JSON object"]
    return payload, []


def _canonical_project_snapshot(payload: dict[str, Any]) -> str | None:
    repository = payload.get("repository")
    head = payload.get("head")
    dirty_digest = payload.get("dirty_digest")
    if (
        not isinstance(repository, str)
        or _is_placeholder(repository)
        or not isinstance(head, str)
        or len(head) < 7
        or any(character not in "0123456789abcdef" for character in head.casefold())
        or not isinstance(dirty_digest, str)
        or len(dirty_digest) != 64
        or any(character not in "0123456789abcdef" for character in dirty_digest.casefold())
    ):
        return None
    return f"{repository}@{head}+dirty:{dirty_digest[:12]}"


def _exact_field_failures(payload: dict[str, Any], expected: set[str], *, label: str) -> list[str]:
    actual = set(payload)
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    failures: list[str] = []
    if missing:
        failures.append(f"{label} missing fields: {missing}")
    if unexpected:
        failures.append(f"{label} has unexpected fields: {unexpected}")
    return failures


def _runtime_common_failures(
    payload: dict[str, Any],
    *,
    kind: str,
    result: dict[str, Any],
    profile_data: dict[str, Any] | None,
    now: dt.datetime,
    max_evidence_age_days: int,
) -> list[str]:
    label = f"{kind} artifact"
    failures = _exact_field_failures(payload, RUNTIME_ARTIFACT_FIELDS[kind], label=label)
    if payload.get("schema_version") != 1:
        failures.append(f"{label} schema_version must be 1")
    if payload.get("kind") != kind:
        failures.append(f"{label} kind does not match artifact kind")
    if payload.get("case_id") != result.get("id"):
        failures.append(f"{label} case_id does not match result id")
    expected_profile = profile_data.get("id") if isinstance(profile_data, dict) else None
    if payload.get("profile") != expected_profile:
        failures.append(f"{label} profile does not match selected profile")
    if payload.get("runtime_target") != result.get("runtime_target"):
        failures.append(f"{label} runtime_target does not match result runtime_target")
    if payload.get("source_snapshot") != result.get("project_snapshot"):
        failures.append(f"{label} source_snapshot does not match result project_snapshot")
    failures.extend(
        _timestamp_failures(
            payload.get("timestamp"),
            label=f"{label} timestamp",
            now=now,
            max_evidence_age_days=max_evidence_age_days,
        )
    )
    if "editor_instance_id" in RUNTIME_ARTIFACT_FIELDS[kind] and (
        not isinstance(payload.get("editor_instance_id"), str)
        or _is_placeholder(payload.get("editor_instance_id"))
    ):
        failures.append(f"{label} editor_instance_id must be substantive")
    return failures


def _validate_runtime_artifact_content(
    *,
    kind: str,
    payload: dict[str, Any],
    result: dict[str, Any],
    profile_data: dict[str, Any] | None,
    now: dt.datetime,
    max_evidence_age_days: int,
) -> list[str]:
    label = f"{kind} artifact"
    failures = _runtime_common_failures(
        payload,
        kind=kind,
        result=result,
        profile_data=profile_data,
        now=now,
        max_evidence_age_days=max_evidence_age_days,
    )
    if kind == "runtime-audit":
        if payload.get("workflow") != result.get("workflow"):
            failures.append(f"{label} workflow does not match result workflow")
        expected_capabilities = (
            profile_data.get("runner_capabilities") if isinstance(profile_data, dict) else None
        )
        if payload.get("runner_capabilities") != expected_capabilities:
            failures.append(f"{label} runner_capabilities do not match selected profile")
        if payload.get("status") != "PASS":
            failures.append(f"{label} status must be PASS")
        if payload.get("command") != result.get("command"):
            failures.append(f"{label} command does not match result command")
        checks = payload.get("checks")
        if not isinstance(checks, dict) or set(checks) != RUNTIME_CHECK_FIELDS:
            failures.append(f"{label} checks must contain the exact runtime verification set")
        elif any(value is not True for value in checks.values()):
            failures.append(f"{label} requires every runtime check to pass")
        screenshot_available = payload.get("screenshot_available")
        reason = payload.get("screenshot_unavailable_reason")
        if not isinstance(screenshot_available, bool):
            failures.append(f"{label} screenshot_available must be boolean")
        elif screenshot_available:
            if reason is not None:
                failures.append(f"{label} screenshot_unavailable_reason must be null when available")
        elif not isinstance(reason, str) or _is_placeholder(reason) or len(reason.strip()) < 16:
            failures.append(f"{label} requires a substantive screenshot unavailability reason")
    elif kind == "mcp-transcript":
        tool_calls = payload.get("tool_calls")
        observed_pairs: dict[str, list[tuple[tuple[str, str], dict[str, Any]]]] = {}
        seen_call_ids: set[str] = set()
        if not isinstance(tool_calls, list):
            failures.append(f"{label} requires substantive MCP tool calls")
        else:
            if len(tool_calls) < 7:
                failures.append(f"{label} requires substantive MCP tool calls")
            for index, call in enumerate(tool_calls):
                if not isinstance(call, dict) or set(call) != MCP_TOOL_CALL_FIELDS:
                    failures.append(f"{label} tool call {index} must use exact fields")
                    continue
                for field in ("call_id", "tool", "operation", "artifact_kind", "artifact_path"):
                    if not isinstance(call.get(field), str) or _is_placeholder(call.get(field)):
                        failures.append(f"{label} tool call {index} {field} must be substantive")
                call_id = call.get("call_id")
                if isinstance(call_id, str):
                    if call_id in seen_call_ids:
                        failures.append(f"{label} tool call ids must be distinct")
                    seen_call_ids.add(call_id)
                operation = call.get("operation")
                artifact_kind = call.get("artifact_kind")
                if isinstance(artifact_kind, str):
                    if isinstance(call.get("tool"), str) and isinstance(operation, str):
                        pair = (
                            _normalized_unity_mcp_tool(call["tool"]),
                            operation.casefold(),
                        )
                        observed_pairs.setdefault(artifact_kind, []).append((pair, call))
                        if pair not in UNITY_MCP_ARTIFACT_TOOL_OPERATIONS.get(
                            artifact_kind, set()
                        ):
                            failures.append(
                                f"{label} tool call {index} does not use an approved Unity MCP "
                                f"tool/operation for {artifact_kind}: {pair[0]}/{pair[1]}"
                            )
                        is_test_job_call = (
                            artifact_kind in UNITY_MCP_TEST_RESULT_MODES
                            and pair[0] in {"run_tests", "get_test_job"}
                        )
                        job_id = call.get("job_id")
                        if is_test_job_call:
                            if not isinstance(job_id, str) or _is_placeholder(job_id):
                                failures.append(
                                    f"{label} tool call {index} test job_id must be substantive"
                                )
                        elif job_id is not None:
                            failures.append(
                                f"{label} tool call {index} job_id must be null outside test jobs"
                            )
                if call.get("status") != "PASS":
                    failures.append(f"{label} tool call {index} status must be PASS")
                if call.get("case_id") != payload.get("case_id"):
                    failures.append(f"{label} tool call {index} case_id does not match transcript")
                if call.get("editor_instance_id") != payload.get("editor_instance_id"):
                    failures.append(f"{label} tool call {index} editor_instance_id does not match transcript")
                if call.get("source_snapshot") != payload.get("source_snapshot"):
                    failures.append(f"{label} tool call {index} source_snapshot does not match transcript")
                digest = call.get("artifact_sha256")
                if not isinstance(digest, str) or len(digest) != 64 or any(
                    character not in "0123456789abcdef" for character in digest
                ):
                    failures.append(f"{label} tool call {index} artifact_sha256 must be lowercase sha256")
                try:
                    _normalized_artifact_path(call.get("artifact_path"))
                except ValueError as error:
                    failures.append(f"{label} tool call {index}: {error}")
            for artifact_kind, required_groups in UNITY_MCP_REQUIRED_OPERATION_GROUPS.items():
                pairs = {pair for pair, _ in observed_pairs.get(artifact_kind, [])}
                for required_group in required_groups:
                    if pairs.isdisjoint(required_group):
                        required = " or ".join(
                            f"{tool}/{operation}" for tool, operation in sorted(required_group)
                        )
                        failures.append(
                            f"{label} requires {required} for {artifact_kind}"
                        )
            observed_test_jobs: dict[str, str] = {}
            for artifact_kind, mode in UNITY_MCP_TEST_RESULT_MODES.items():
                calls = observed_pairs.get(artifact_kind, [])
                starts = [
                    call for pair, call in calls if pair == ("run_tests", mode)
                ]
                completions = [
                    call for pair, call in calls if pair == ("get_test_job", mode)
                ]
                if len(starts) != 1 or len(completions) != 1:
                    failures.append(
                        f"{label} {artifact_kind} requires exactly one run_tests start and "
                        "one get_test_job completion"
                    )
                    continue
                start_job = starts[0].get("job_id")
                completion_job = completions[0].get("job_id")
                if start_job != completion_job:
                    failures.append(
                        f"{label} {artifact_kind} test job start and completion must share job_id"
                    )
                elif isinstance(start_job, str):
                    observed_test_jobs[artifact_kind] = start_job
            if len(set(observed_test_jobs.values())) != len(observed_test_jobs):
                failures.append(f"{label} EditMode and PlayMode test jobs must be distinct")
    elif kind == "editor-state":
        if payload.get("ready") is not True:
            failures.append(f"{label} ready must be true")
        if payload.get("compiling") is not False:
            failures.append(f"{label} compiling must be false")
        if type(payload.get("compile_errors")) is not int or payload.get("compile_errors") != 0:
            failures.append(f"{label} compile_errors must be zero")
    elif kind in {"editmode-result", "playmode-result"}:
        if payload.get("status") != "PASS":
            failures.append(f"{label} status must be PASS")
        if type(payload.get("tests")) is not int or payload.get("tests", 0) < 1:
            failures.append(f"{label} tests must be greater than zero")
        if type(payload.get("failures")) is not int or payload.get("failures") != 0:
            failures.append(f"{label} failures must be zero")
    elif kind == "console-report":
        if type(payload.get("errors")) is not int or payload.get("errors") != 0:
            failures.append(f"{label} errors must be zero")
        if type(payload.get("warnings")) is not int or payload.get("warnings", -1) < 0:
            failures.append(f"{label} warnings must be a non-negative integer")
    elif kind == "runtime-assertion":
        if payload.get("status") != "PASS":
            failures.append(f"{label} status must be PASS")
        assertions = payload.get("assertions")
        if not isinstance(assertions, list) or len(assertions) < 2:
            failures.append(f"{label} requires at least two substantive assertions")
        else:
            for index, assertion in enumerate(assertions):
                if not isinstance(assertion, dict) or set(assertion) != {"name", "passed", "observed"}:
                    failures.append(f"{label} assertion {index} must use exact fields")
                    continue
                if not isinstance(assertion.get("name"), str) or _is_placeholder(assertion.get("name")):
                    failures.append(f"{label} assertion {index} name must be substantive")
                if assertion.get("passed") is not True:
                    failures.append(f"{label} assertion {index} must pass")
                observed = assertion.get("observed")
                if not isinstance(observed, str) or _is_placeholder(observed) or len(observed.strip()) < 16:
                    failures.append(f"{label} assertion {index} observed value must be substantive")
    return failures


def _validate_runtime_artifact_set(
    artifacts: dict[str, Path],
    *,
    result: dict[str, Any],
) -> list[str]:
    failures: list[str] = []
    if not any(kind in artifacts for kind in RUNTIME_ARTIFACT_FIELDS):
        return failures
    result_refs = {
        artifact["kind"]: artifact
        for artifact in result.get("artifacts", [])
        if isinstance(artifact, dict) and isinstance(artifact.get("kind"), str)
    }
    editor_instances: dict[str, str] = {}
    for kind in {*RUNTIME_ARTIFACT_FIELDS, "command-log"}:
        path = artifacts.get(kind)
        if path is None:
            continue
        payload, _ = _json_object(path, label=f"{kind} artifact")
        if payload is not None and isinstance(payload.get("editor_instance_id"), str):
            editor_instances[kind] = payload["editor_instance_id"]
    if len(set(editor_instances.values())) > 1:
        failures.append(
            "runtime artifacts must bind to one editor_instance_id: "
            + ", ".join(f"{kind}={value}" for kind, value in sorted(editor_instances.items()))
        )
    audit_path = artifacts.get("runtime-audit")
    if audit_path is not None:
        audit, _ = _json_object(audit_path, label="runtime-audit artifact")
        if audit is not None:
            manifest = audit.get("artifact_manifest")
            expected_manifest_kinds = set(RUNTIME_MANIFEST_KINDS)
            screenshot_present = "screenshot" in artifacts
            if screenshot_present:
                expected_manifest_kinds.add("screenshot")
            manifested_kinds: set[str] = set()
            manifested_paths: set[str] = set()
            if not isinstance(manifest, list) or not manifest:
                failures.append("runtime-audit artifact_manifest must bind runtime provenance artifacts")
            else:
                for index, artifact in enumerate(manifest):
                    label = f"runtime-audit artifact_manifest[{index}]"
                    if not isinstance(artifact, dict) or set(artifact) != RUNTIME_MANIFEST_FIELDS:
                        failures.append(f"{label} must contain kind, path, and sha256")
                        continue
                    kind = artifact.get("kind")
                    if not isinstance(kind, str) or kind not in expected_manifest_kinds:
                        failures.append(f"{label} has unexpected kind: {kind}")
                        continue
                    if kind in manifested_kinds:
                        failures.append(f"runtime-audit artifact_manifest has duplicate kind: {kind}")
                    manifested_kinds.add(kind)
                    try:
                        normalized = _normalized_artifact_path(artifact.get("path"))
                    except ValueError as error:
                        failures.append(f"{label}: {error}")
                        continue
                    if normalized in manifested_paths:
                        failures.append("runtime-audit artifact_manifest paths must be distinct")
                    manifested_paths.add(normalized)
                    expected_ref = result_refs.get(kind)
                    if expected_ref is None:
                        failures.append(f"{label} does not reference a result artifact")
                    else:
                        for field in ("path", "sha256"):
                            if artifact.get(field) != expected_ref.get(field):
                                failures.append(
                                    f"{label} {field} does not match result artifact {kind}"
                                )
            if manifested_kinds != expected_manifest_kinds:
                failures.append(
                    "runtime-audit artifact_manifest must contain exactly "
                    f"{sorted(expected_manifest_kinds)}"
                )
            if audit.get("screenshot_available") is True and not screenshot_present:
                failures.append("runtime-audit artifact declares a screenshot but no screenshot artifact exists")
            if audit.get("screenshot_available") is False and screenshot_present:
                failures.append("runtime-audit artifact declares no screenshot but a screenshot artifact exists")
    transcript_path = artifacts.get("mcp-transcript")
    if transcript_path is not None:
        transcript, _ = _json_object(transcript_path, label="mcp-transcript artifact")
        if transcript is not None and isinstance(transcript.get("tool_calls"), list):
            expected_call_artifacts = {
                "editor-state",
                "editmode-result",
                "playmode-result",
                "console-report",
                "runtime-assertion",
            }
            called_artifacts: set[str] = set()
            for index, call in enumerate(transcript["tool_calls"]):
                if not isinstance(call, dict):
                    continue
                artifact_kind = call.get("artifact_kind")
                if not isinstance(artifact_kind, str):
                    continue
                called_artifacts.add(artifact_kind)
                expected_ref = result_refs.get(artifact_kind)
                if expected_ref is None:
                    failures.append(
                        f"mcp-transcript tool call {index} does not reference a result artifact"
                    )
                    continue
                for call_field, result_field in (
                    ("artifact_path", "path"),
                    ("artifact_sha256", "sha256"),
                ):
                    if call.get(call_field) != expected_ref.get(result_field):
                        failures.append(
                            f"mcp-transcript tool call {index} {call_field} "
                            f"does not match result artifact {artifact_kind}"
                        )
            if called_artifacts != expected_call_artifacts:
                failures.append(
                    "mcp-transcript tool calls must bind exactly "
                    f"{sorted(expected_call_artifacts)}"
                )
    screenshot = artifacts.get("screenshot")
    if screenshot is not None and screenshot.stat().st_size == 0:
        failures.append("screenshot artifact must not be empty")
    return failures


def _validate_artifact_content(
    *,
    kind: str,
    path: Path,
    result: dict[str, Any],
    profile_data: dict[str, Any] | None,
    now: dt.datetime,
    max_evidence_age_days: int,
) -> list[str]:
    failures: list[str] = []
    if kind == "project-snapshot":
        payload, errors = _json_object(path, label="project-snapshot artifact")
        failures.extend(errors)
        if payload is None:
            return failures
        canonical = _canonical_project_snapshot(payload)
        if canonical is None:
            failures.append("project-snapshot artifact has invalid canonical identity fields")
        elif result.get("project_snapshot") != canonical:
            failures.append("project_snapshot does not match project-snapshot artifact")
        if profile_data is not None:
            project = profile_data.get("project")
            expected_name = project.get("name") if isinstance(project, dict) else None
            if payload.get("repository") != expected_name:
                failures.append("project-snapshot repository does not match profile project identity")
        if not isinstance(payload.get("dirty"), bool):
            failures.append("project-snapshot artifact dirty must be boolean")
        scope_digest = payload.get("scope_digest")
        if not isinstance(scope_digest, str) or len(scope_digest) != 64 or any(
            character not in "0123456789abcdef" for character in scope_digest.casefold()
        ):
            failures.append("project-snapshot artifact scope_digest must be lowercase sha256")
        failures.extend(
            _timestamp_failures(
                payload.get("captured_at"),
                label="project-snapshot artifact captured_at",
                now=now,
                max_evidence_age_days=max_evidence_age_days,
            )
        )
    elif kind == "command-log":
        payload, errors = _json_object(path, label="command-log artifact")
        failures.extend(errors)
        if payload is None:
            return failures
        if payload.get("command") != result.get("command"):
            failures.append("command-log command does not match result command")
        if payload.get("exit_code") != result.get("exit_code"):
            failures.append("command-log exit_code does not match result exit_code")
        if payload.get("runtime_target") != result.get("runtime_target"):
            failures.append("command-log runtime_target does not match result runtime_target")
        if result.get("id") == "fpc-unity-localization-runtime":
            expected_runtime_fields = {
                "case_id": result.get("id"),
                "profile": profile_data.get("id") if isinstance(profile_data, dict) else None,
                "source_snapshot": result.get("project_snapshot"),
            }
            for field, value in expected_runtime_fields.items():
                if payload.get(field) != value:
                    failures.append(f"command-log {field} does not match runtime result")
            if not isinstance(payload.get("editor_instance_id"), str) or _is_placeholder(
                payload.get("editor_instance_id")
            ):
                failures.append("command-log editor_instance_id must be substantive for runtime evidence")
        if not isinstance(payload.get("stdout"), str) or not isinstance(payload.get("stderr"), str):
            failures.append("command-log stdout and stderr must be strings")
        failures.extend(
            _timestamp_failures(
                payload.get("captured_at"),
                label="command-log captured_at",
                now=now,
                max_evidence_age_days=max_evidence_age_days,
            )
        )
    elif kind == "verdict":
        payload, errors = _json_object(path, label="verdict artifact")
        failures.extend(errors)
        if payload is None:
            return failures
        if payload.get("verdict") != result.get("verdict"):
            failures.append("verdict artifact does not match result verdict")
        if payload.get("reason") != result.get("reason"):
            failures.append("verdict artifact reason does not match result reason")
    elif (kind == "report" or kind.endswith("-report")) and kind not in RUNTIME_ARTIFACT_FIELDS:
        try:
            content = path.read_text(encoding="utf-8").strip()
        except (OSError, UnicodeDecodeError) as error:
            failures.append(f"{kind} artifact must be UTF-8 text: {error}")
        else:
            if len(content) < 8 or _is_placeholder(content):
                failures.append(f"{kind} artifact has no substantive report content")
    elif kind in RUNTIME_ARTIFACT_FIELDS:
        payload, errors = _json_object(path, label=f"{kind} artifact")
        failures.extend(errors)
        if payload is not None:
            failures.extend(
                _validate_runtime_artifact_content(
                    kind=kind,
                    payload=payload,
                    result=result,
                    profile_data=profile_data,
                    now=now,
                    max_evidence_age_days=max_evidence_age_days,
                )
            )
    return failures


def _artifact_kinds(value: Any) -> set[str]:
    if not isinstance(value, list):
        return set()
    return {
        str(item.get("kind"))
        for item in value
        if isinstance(item, dict) and isinstance(item.get("kind"), str) and item.get("path")
    }


def _validate_pass(
    case: dict[str, Any],
    result: dict[str, Any],
    artifact_root: Path,
    *,
    profile_data: dict[str, Any] | None,
    now: dt.datetime,
) -> list[str]:
    failures: list[str] = []
    max_evidence_age_days = (
        profile_data["max_evidence_age_days"]
        if profile_data is not None
        else DEFAULT_MAX_EVIDENCE_AGE_DAYS
    )
    if result.get("evidence_label") != "Verified":
        failures.append("PASS requires evidence_label Verified")
    if result.get("exit_code") != 0:
        failures.append("PASS requires exit_code 0")
    for field in ("runtime_target", "command", "project_snapshot", "reviewer", "restore"):
        if not isinstance(result.get(field), str) or _is_placeholder(result.get(field)):
            failures.append(f"{field} is required and must not be a placeholder")
    if profile_data is not None:
        allowed_runtime_targets = profile_data.get("runtime_targets")
        if (
            not isinstance(allowed_runtime_targets, list)
            or result.get("runtime_target") not in allowed_runtime_targets
        ):
            failures.append("runtime_target is not selected by profile runtime_targets")
    failures.extend(
        _timestamp_failures(
            result.get("timestamp"),
            label="timestamp",
            now=now,
            max_evidence_age_days=max_evidence_age_days,
        )
    )
    if result.get("unauthorized_write") is not False:
        failures.append("unauthorized_write must be false")
    missing = sorted(set(case["required_artifacts"]) - _artifact_kinds(result.get("artifacts")))
    if missing:
        failures.append(f"missing required artifact kinds: {missing}")
    seen_kinds: set[str] = set()
    seen_paths: set[str] = set()
    resolved_artifacts: dict[str, Path] = {}
    for artifact in result.get("artifacts", []):
        kind = artifact["kind"]
        if kind in seen_kinds:
            failures.append(f"duplicate artifact kind: {kind}")
        seen_kinds.add(kind)
        try:
            normalized_path = _normalized_artifact_path(artifact["path"])
        except ValueError as error:
            failures.append(str(error))
            continue
        if normalized_path in seen_paths:
            failures.append(f"duplicate artifact path: {artifact['path']}")
        seen_paths.add(normalized_path)
        try:
            path = _resolve_artifact(artifact_root, artifact["path"])
        except ValueError as error:
            failures.append(str(error))
            continue
        if _sha256_path(path) != artifact["sha256"]:
            failures.append(f"artifact sha256 mismatch: {artifact['path']}")
            continue
        resolved_artifacts[kind] = path
    required_paths = [
        resolved_artifacts[kind]
        for kind in case["required_artifacts"]
        if kind in resolved_artifacts
    ]
    if len(set(required_paths)) != len(required_paths):
        failures.append("required artifact kinds must use distinct files")
    for kind, path in resolved_artifacts.items():
        failures.extend(
            _validate_artifact_content(
                kind=kind,
                path=path,
                result=result,
                profile_data=profile_data,
                now=now,
                max_evidence_age_days=max_evidence_age_days,
            )
        )
    failures.extend(_validate_runtime_artifact_set(resolved_artifacts, result=result))
    return failures


def evaluate_results(
    root: Path | str,
    results_path: Path | str | None,
    *,
    artifact_root: Path | str | None = None,
    profile: str | None = None,
    now: dt.datetime | None = None,
) -> dict[str, Any]:
    current = now or dt.datetime.now(dt.timezone.utc)
    if current.tzinfo is None or current.utcoffset() is None:
        raise ValueError("now must be timezone-aware")
    profile_data = load_profile(root, profile) if profile is not None else None
    cases = load_cases(root, profile=profile)
    expected = {case["id"]: case for case in cases}
    if results_path is None or not Path(results_path).exists():
        return {
            "verdict": "BLOCKED",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": [],
            "blocked": ["No governed game-project dogfood results were supplied"],
            "legacy_format": False,
            "profile": profile,
        }
    results_file = Path(results_path).resolve()
    approved_artifact_root = (
        Path(artifact_root).resolve() if artifact_root is not None else results_file.parent
    )
    try:
        results, legacy_format, schema_failures = _load_results(Path(root).resolve(), results_file)
    except (OSError, json.JSONDecodeError) as error:
        return {
            "verdict": "FAIL",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": [str(error)],
            "blocked": [],
            "legacy_format": False,
            "profile": profile,
        }
    if schema_failures:
        return {
            "verdict": "FAIL",
            "total_cases": len(cases),
            "observed_cases": 0,
            "passed": 0,
            "unique_ids": 0,
            "failures": schema_failures,
            "blocked": [],
            "legacy_format": legacy_format,
            "profile": profile,
        }

    by_id: dict[str, dict[str, Any]] = {}
    failures: list[str] = []
    blocked: list[str] = []
    for result in results:
        if not isinstance(result, dict) or not isinstance(result.get("id"), str):
            failures.append("every result requires a string id")
            continue
        result_id = result["id"]
        if result_id in by_id:
            failures.append(f"duplicate result id: {result_id}")
            continue
        by_id[result_id] = result
    missing = sorted(set(expected) - set(by_id))
    extra = sorted(set(by_id) - set(expected))
    failures.extend(f"missing result: {item}" for item in missing)
    failures.extend(f"unknown result: {item}" for item in extra)
    passed = 0
    for result_id, case in expected.items():
        result = by_id.get(result_id)
        if result is None:
            continue
        if result.get("workflow") != case["workflow"]:
            failures.append(f"{result_id}: workflow does not match case")
        verdict = result.get("verdict")
        if verdict == "PASS":
            case_failures = _validate_pass(
                case,
                result,
                approved_artifact_root,
                profile_data=profile_data,
                now=current,
            )
            failures.extend(f"{result_id}: {reason}" for reason in case_failures)
            if not case_failures:
                passed += 1
        elif verdict == "BLOCKED":
            if result.get("evidence_label") != "BLOCKED" or not result.get("reason"):
                failures.append(f"{result_id}: BLOCKED requires evidence_label and reason")
            else:
                blocked.append(result_id)
        elif verdict == "FAIL":
            if result.get("evidence_label") not in EVIDENCE_LABELS or not result.get("reason"):
                failures.append(f"{result_id}: FAIL requires evidence_label and reason")
            else:
                failures.append(f"{result_id}: runner reported FAIL: {result['reason']}")
        else:
            failures.append(f"{result_id}: verdict must be PASS, FAIL, or BLOCKED")
    if failures:
        verdict = "FAIL"
    elif blocked:
        verdict = "BLOCKED"
    else:
        verdict = "PASS"
    return {
        "verdict": verdict,
        "total_cases": len(cases),
        "observed_cases": len(by_id),
        "passed": passed,
        "unique_ids": len(by_id),
        "failures": failures,
        "blocked": blocked,
        "legacy_format": legacy_format,
        "profile": profile,
    }


def write_summaries(
    root: Path | str,
    results_path: Path | str,
    output_root: Path | str,
    *,
    artifact_root: Path | str | None = None,
    profile: str | None = None,
) -> list[Path]:
    report = evaluate_results(root, results_path, artifact_root=artifact_root, profile=profile)
    if report["verdict"] != "PASS":
        raise ValueError("dogfood summaries require a complete PASS result set")
    if report["legacy_format"]:
        raise ValueError("dogfood summaries require the strict results wrapper")
    results_file = Path(results_path).resolve()
    approved_artifact_root = (
        Path(artifact_root).resolve() if artifact_root is not None else results_file.parent
    )
    results, _, schema_failures = _load_results(Path(root).resolve(), results_file)
    if schema_failures:
        raise ValueError("dogfood result schema is invalid: " + "; ".join(schema_failures))
    result_by_id = {item["id"]: item for item in results}
    written: list[Path] = []
    output_path = Path(output_root)
    for case in load_cases(root, profile=profile):
        result = result_by_id[case["id"]]
        summary_path = output_path / case["id"] / "dogfood-summary.json"
        summary_path.parent.mkdir(parents=True, exist_ok=True)
        summary_path.write_text(
            json.dumps(
                {
                    "_generated": GENERATED_MARKER,
                    "label": "Verified",
                    "workflow": case["workflow"],
                    "case_id": case["id"],
                    "exit_code": 0,
                    "runtime_target": result["runtime_target"],
                    "command": result["command"],
                    "artifact_root": str(approved_artifact_root),
                    "artifacts": result["artifacts"],
                    "project_snapshot": result["project_snapshot"],
                    "reviewer": result["reviewer"],
                    "timestamp": result["timestamp"],
                    "unauthorized_write": False,
                    "restore": result["restore"],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        written.append(summary_path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export and validate governed real-project dogfood scenarios.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--export", type=Path)
    parser.add_argument("--results", type=Path)
    parser.add_argument("--status", type=Path)
    parser.add_argument("--summary-dir", type=Path)
    parser.add_argument("--artifact-root", type=Path)
    parser.add_argument("--profile")
    args = parser.parse_args(argv)
    if args.summary_dir and not args.results:
        parser.error("--summary-dir requires --results")
    if args.export:
        print(f"dogfood-export: {export_cases(args.root, args.export, profile=args.profile)} cases")
    if args.status:
        write_blocked_status(args.status, "No governed Hermes runner and real game-project snapshot were supplied")
        print(args.status)
    if args.results:
        report = evaluate_results(
            args.root,
            args.results,
            artifact_root=args.artifact_root,
            profile=args.profile,
        )
        print(json.dumps(report, indent=2))
        if report["verdict"] == "PASS" and args.summary_dir:
            written = write_summaries(
                args.root,
                args.results,
                args.summary_dir,
                artifact_root=args.artifact_root,
                profile=args.profile,
            )
            print(f"dogfood-summaries: {len(written)} written to {args.summary_dir}")
        return 0 if report["verdict"] == "PASS" else 2 if report["verdict"] == "BLOCKED" else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
