from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator
from jsonschema.exceptions import SchemaError
from referencing.exceptions import Unresolvable

try:
    from scripts.studio_experience import task_packet_semantic_errors
except ModuleNotFoundError:  # direct execution from the scripts directory
    from studio_experience import task_packet_semantic_errors


EVIDENCE_LABELS = {"Verified", "Snapshot", "Unverified", "BLOCKED"}
GENERATED_MARKER = "Generated by scripts/runner_eval.py. Do not edit manually."
ARTIFACT_SCHEMA_FILES = {
    "studio-task-packet": "studio-task-packet.schema.json",
    "studio-evidence-card": "studio-evidence-card.schema.json",
}
DEFAULT_ARTIFACT_SCHEMA_ROOT = Path(__file__).resolve().parents[1] / "evals" / "schema"
RESULT_COMMON_REQUIRED_FIELDS = {
    "id",
    "selected_skill",
    "mutated",
    "artifact",
    "evidence_labels",
}
TASK_PACKET_EXPECTED_FIELDS = {"role", "intent", "golden_path", "status"}


@dataclass(frozen=True)
class RunnerEvalSummary:
    verdict: str
    total: int
    passed: int
    failures: list[str]


def load_cases(root: Path | str, kind: str) -> list[dict[str, Any]]:
    root_path = Path(root).resolve()
    case_dir = root_path / "evals" / kind
    cases: list[dict[str, Any]] = []
    for path in sorted(case_dir.glob("*.json")) if case_dir.exists() else []:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for raw in payload.get("cases", []):
            case = dict(raw)
            case["kind"] = kind
            case.setdefault("allow_mutation", False)
            case.setdefault("required_artifact_fields", [])
            cases.append(case)
    return cases


def export_cases(root: Path | str, kind: str, output: Path | str) -> int:
    cases = load_cases(root, kind)
    output_path = Path(output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "".join(json.dumps(case, sort_keys=True, ensure_ascii=False) + "\n" for case in cases),
        encoding="utf-8",
    )
    return len(cases)


def _failure(verdict: str, total: int, failures: list[str], passed: int = 0) -> dict[str, Any]:
    return {"verdict": verdict, "total": total, "passed": passed, "failures": failures}


def _is_null_or_blank(value: object) -> bool:
    return value is None or (isinstance(value, str) and not value.strip())


def _validate_artifact_contracts(
    case_id: str,
    case: dict[str, Any],
    result: dict[str, Any],
    artifact: dict[str, Any],
    schema_root: Path,
) -> list[str]:
    contracts = case.get("artifact_contracts")
    if contracts is None:
        if any(
            field in case
            for field in (
                "required_workflow_artifact_fields",
                "allow_empty_workflow_artifact_fields",
            )
        ):
            return [
                f"{case_id}: workflow artifact metadata requires "
                "artifact_contracts"
            ]
        if "allow_blocked_task_packet" in case:
            return [
                f"{case_id}: allow_blocked_task_packet requires artifact_contracts"
            ]
        if "allow_ambiguous_task_packet" in case:
            return [
                f"{case_id}: allow_ambiguous_task_packet requires artifact_contracts"
            ]
        if "expected_task_packet" in case:
            return [
                f"{case_id}: expected_task_packet requires artifact_contracts"
            ]
        return []
    if not isinstance(contracts, dict) or not contracts:
        return [f"{case_id}: artifact_contracts must be a non-empty object"]

    failures: list[str] = []
    validated_contract_fields: set[str] = set()
    for artifact_field, contract_name in contracts.items():
        if not isinstance(artifact_field, str) or not artifact_field.strip():
            failures.append(f"{case_id}: artifact contract field must be non-blank")
            continue
        if not isinstance(contract_name, str) or not contract_name.strip():
            failures.append(
                f"{case_id}: artifact contract {artifact_field} must name a "
                "non-blank string"
            )
            continue
        if contract_name not in ARTIFACT_SCHEMA_FILES:
            failures.append(
                f"{case_id}: unknown artifact contract {contract_name!r}"
            )
            continue
        payload = artifact.get(artifact_field)
        if not isinstance(payload, dict):
            failures.append(f"{case_id}: {artifact_field} must be an object")
            continue
        schema_path = schema_root / ARTIFACT_SCHEMA_FILES[contract_name]
        try:
            schema = json.loads(schema_path.read_text(encoding="utf-8"))
            Draft202012Validator.check_schema(schema)
        except SchemaError as error:
            failures.append(
                f"{case_id}: invalid artifact contract {contract_name}: "
                f"{error.message}"
            )
            continue
        except (OSError, json.JSONDecodeError) as error:
            failures.append(
                f"{case_id}: cannot load artifact contract {contract_name}: {error}"
            )
            continue
        try:
            validator = Draft202012Validator(schema)
            validation_errors = sorted(
                validator.iter_errors(payload),
                key=lambda error: tuple(
                    str(part) for part in error.absolute_path
                ),
            )
        except Unresolvable as error:
            failures.append(
                f"{case_id}: unresolvable artifact contract {contract_name}: "
                f"{error}"
            )
            continue
        if validation_errors:
            failures.append(
                f"{case_id}: {artifact_field} violates {contract_name}: "
                f"{validation_errors[0].message}"
            )
        else:
            validated_contract_fields.add(artifact_field)

    expected_task_packet = case.get("expected_task_packet")
    expected_task_packet_valid = False
    if "expected_task_packet" in case:
        if not isinstance(expected_task_packet, dict) or not expected_task_packet:
            failures.append(
                f"{case_id}: expected_task_packet must be a non-empty object"
            )
        else:
            unknown_fields = sorted(
                set(expected_task_packet) - TASK_PACKET_EXPECTED_FIELDS
            )
            missing_fields = sorted(
                TASK_PACKET_EXPECTED_FIELDS - set(expected_task_packet)
            )
            if unknown_fields or missing_fields:
                details: list[str] = []
                if unknown_fields:
                    details.append(f"unknown fields {unknown_fields}")
                if missing_fields:
                    details.append(f"missing fields {missing_fields}")
                failures.append(
                    f"{case_id}: expected_task_packet requires exactly role, "
                    f"intent, golden_path, status ({'; '.join(details)})"
                )
            if contracts.get("task_packet") != "studio-task-packet":
                failures.append(
                    f"{case_id}: expected_task_packet requires the task_packet "
                    "artifact contract"
                )
            invalid_string_fields = sorted(
                field
                for field in ("role", "intent", "status")
                if field in expected_task_packet
                and (
                    not isinstance(expected_task_packet[field], str)
                    or not expected_task_packet[field].strip()
                )
            )
            if invalid_string_fields:
                failures.append(
                    f"{case_id}: expected_task_packet requires non-blank string "
                    f"fields {invalid_string_fields}"
                )
            if "golden_path" in expected_task_packet:
                golden_path = expected_task_packet["golden_path"]
                if golden_path is not None and not isinstance(golden_path, str):
                    failures.append(
                        f"{case_id}: expected_task_packet golden_path must be a "
                        "string or null"
                    )
            expected_task_packet_valid = not (
                unknown_fields
                or missing_fields
                or invalid_string_fields
                or (
                    "golden_path" in expected_task_packet
                    and expected_task_packet["golden_path"] is not None
                    and not isinstance(expected_task_packet["golden_path"], str)
                )
            )

    allow_blocked_task_packet = case.get("allow_blocked_task_packet", False)
    if not isinstance(allow_blocked_task_packet, bool):
        failures.append(f"{case_id}: allow_blocked_task_packet must be boolean")
        allow_blocked_task_packet = False
    elif allow_blocked_task_packet:
        if case.get("expected_verdict") != "BLOCKED":
            failures.append(
                f"{case_id}: allow_blocked_task_packet requires an expected "
                "BLOCKED verdict"
            )
        if case.get("target_skill") != "using-game-studio-skills":
            failures.append(
                f"{case_id}: allow_blocked_task_packet is limited to the "
                "using-game-studio-skills router outcome"
            )
        if result.get("verdict") != "BLOCKED":
            failures.append(
                f"{case_id}: allow_blocked_task_packet requires a BLOCKED result"
            )
        required_contracts = {
            "task_packet": "studio-task-packet",
            "evidence_card": "studio-evidence-card",
        }
        if any(
            contracts.get(field) != contract
            for field, contract in required_contracts.items()
        ):
            failures.append(
                f"{case_id}: allow_blocked_task_packet requires task packet and "
                "evidence card contracts"
            )
        if "workflow_artifact" in artifact:
            failures.append(
                f"{case_id}: allow_blocked_task_packet forbids workflow_artifact"
            )

    allow_ambiguous_task_packet = case.get(
        "allow_ambiguous_task_packet", False
    )
    if not isinstance(allow_ambiguous_task_packet, bool):
        failures.append(
            f"{case_id}: allow_ambiguous_task_packet must be boolean"
        )
        allow_ambiguous_task_packet = False
    elif allow_ambiguous_task_packet:
        if case.get("expected_case_outcome") != "PASS":
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet requires "
                "expected_case_outcome with an expected PASS case outcome"
            )
        if "expected_verdict" in case:
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet forbids expected_verdict"
            )
        if case.get("target_skill") != "using-game-studio-skills":
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet is limited to the "
                "using-game-studio-skills root router outcome"
            )
        if result.get("case_outcome") != "PASS":
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet requires a PASS case "
                "outcome"
            )
        if "verdict" in result:
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet forbids a runtime verdict"
            )
        if contracts.get("task_packet") != "studio-task-packet":
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet requires the task "
                "packet contract"
            )
        if "expected_task_packet" not in case:
            failures.append(
                f"{case_id}: allow_ambiguous_task_packet requires "
                "expected_task_packet"
            )
        for forbidden_field in ("workflow_artifact", "evidence_card"):
            if forbidden_field in artifact:
                failures.append(
                    f"{case_id}: allow_ambiguous_task_packet forbids "
                    f"{forbidden_field}"
                )

    task_packet = artifact.get("task_packet")
    if isinstance(task_packet, dict):
        if "task_packet" in validated_contract_fields:
            for semantic_error in task_packet_semantic_errors(task_packet):
                failures.append(f"{case_id}: task_packet {semantic_error}")
        if expected_task_packet_valid:
            for field in sorted(TASK_PACKET_EXPECTED_FIELDS):
                if task_packet.get(field) != expected_task_packet[field]:
                    failures.append(
                        f"{case_id}: task_packet {field} mismatch"
                    )
        selected_workflow = task_packet.get("selected_workflow")
        if allow_ambiguous_task_packet:
            if task_packet.get("status") != "AMBIGUOUS":
                failures.append(
                    f"{case_id}: allow_ambiguous_task_packet requires task_packet "
                    "status AMBIGUOUS"
                )
            if selected_workflow is not None:
                failures.append(
                    f"{case_id}: allow_ambiguous_task_packet requires no selected "
                    "workflow"
                )
        elif allow_blocked_task_packet:
            if task_packet.get("status") != "BLOCKED":
                failures.append(
                    f"{case_id}: allow_blocked_task_packet requires task_packet "
                    "status BLOCKED"
                )
            if selected_workflow is not None:
                failures.append(
                    f"{case_id}: allow_blocked_task_packet requires no selected "
                    "workflow"
                )
        elif selected_workflow != result.get("selected_skill"):
            failures.append(f"{case_id}: task_packet selected_workflow mismatch")

    evidence_card = artifact.get("evidence_card")
    if isinstance(evidence_card, dict):
        if evidence_card.get("workflow") != result.get("selected_skill"):
            failures.append(f"{case_id}: evidence_card workflow mismatch")
        if evidence_card.get("verdict") != result.get("verdict"):
            failures.append(f"{case_id}: evidence_card verdict mismatch")

    required_workflow_fields = case.get("required_workflow_artifact_fields")
    if required_workflow_fields is not None:
        if not isinstance(required_workflow_fields, list) or any(
            not isinstance(field, str) or not field.strip()
            for field in required_workflow_fields
        ):
            failures.append(
                f"{case_id}: required_workflow_artifact_fields must be a list "
                "of non-blank strings"
            )
        else:
            allow_empty_fields = case.get(
                "allow_empty_workflow_artifact_fields", []
            )
            allowed_empty_fields: set[str] = set()
            if not isinstance(allow_empty_fields, list) or any(
                not isinstance(field, str) or not field.strip()
                for field in allow_empty_fields
            ):
                failures.append(
                    f"{case_id}: allow_empty_workflow_artifact_fields must be "
                    "a list of non-blank strings"
                )
            else:
                unknown_allow_empty_fields = sorted(
                    set(allow_empty_fields) - set(required_workflow_fields)
                )
                if unknown_allow_empty_fields:
                    failures.append(
                        f"{case_id}: allow-empty workflow artifact fields are "
                        f"not required {unknown_allow_empty_fields}"
                    )
                else:
                    allowed_empty_fields = set(allow_empty_fields)
            workflow_artifact = artifact.get("workflow_artifact")
            if not isinstance(workflow_artifact, dict):
                failures.append(f"{case_id}: workflow_artifact must be an object")
            else:
                missing_fields = sorted(
                    set(required_workflow_fields) - set(workflow_artifact)
                )
                if missing_fields:
                    failures.append(
                        f"{case_id}: missing workflow artifact fields {missing_fields}"
                    )
                blank_fields = sorted(
                    field
                    for field in required_workflow_fields
                    if field in workflow_artifact
                    and (
                        _is_null_or_blank(workflow_artifact[field])
                        or (
                            isinstance(workflow_artifact[field], (list, dict))
                            and not workflow_artifact[field]
                            and field not in allowed_empty_fields
                        )
                    )
                )
                if blank_fields:
                    failures.append(
                        f"{case_id}: null, blank, or empty workflow artifact "
                        f"fields {blank_fields}"
                    )
    elif "allow_empty_workflow_artifact_fields" in case:
        failures.append(
            f"{case_id}: allow_empty_workflow_artifact_fields requires "
            "required_workflow_artifact_fields"
        )
    return failures


def validate_runner_results(
    cases: list[dict[str, Any]],
    results: list[Any],
    schema_root: Path | str | None = None,
) -> dict[str, Any]:
    case_ids = [str(case.get("id", "")) for case in cases]
    if not case_ids or any(not case_id for case_id in case_ids):
        return _failure("FAIL", len(cases), ["cases require non-empty ids"])
    if len(set(case_ids)) != len(case_ids):
        return _failure("FAIL", len(cases), ["duplicate case ids"])
    metadata_failures: list[str] = []
    for case_id, case in zip(case_ids, cases, strict=True):
        required_fields = case.get("required_artifact_fields")
        if (
            not isinstance(required_fields, list)
            or not required_fields
            or any(
                not isinstance(field, str) or not field.strip()
                for field in required_fields
            )
            or len(required_fields) != len(set(required_fields))
        ):
            metadata_failures.append(
                f"{case_id}: required_artifact_fields must be a non-empty list "
                "of unique nonblank strings"
            )
    if metadata_failures:
        return _failure("FAIL", len(cases), metadata_failures)
    if not results:
        return _failure("BLOCKED", len(cases), ["no governed runner results were supplied"])

    malformed_result_indexes = [
        index for index, result in enumerate(results) if not isinstance(result, dict)
    ]
    if malformed_result_indexes:
        return _failure(
            "FAIL",
            len(cases),
            [
                "runner result elements must be objects at indexes "
                f"{malformed_result_indexes}"
            ],
        )

    result_ids = [str(result.get("id", "")) for result in results]
    failures: list[str] = []
    if len(set(result_ids)) != len(result_ids):
        failures.append("duplicate result ids")
    expected_ids = set(case_ids)
    observed_ids = set(result_ids)
    missing = sorted(expected_ids - observed_ids)
    unknown = sorted(observed_ids - expected_ids)
    if missing:
        failures.append(f"missing result ids: {missing}")
    if unknown:
        failures.append(f"unknown result ids: {unknown}")
    if failures:
        return _failure("FAIL", len(cases), failures)

    case_by_id = {case_id: case for case_id, case in zip(case_ids, cases, strict=True)}
    result_by_id = {result_id: result for result_id, result in zip(result_ids, results, strict=True)}
    passed = 0
    for case_id in case_ids:
        case = case_by_id[case_id]
        result = result_by_id[case_id]
        routing_evaluation = case.get("allow_ambiguous_task_packet") is True
        outcome_fields = {"case_outcome"} if routing_evaluation else {"verdict"}
        missing_fields = sorted(
            (RESULT_COMMON_REQUIRED_FIELDS | outcome_fields) - set(result)
        )
        if missing_fields:
            failures.append(f"{case_id}: missing fields {missing_fields}")
        if result.get("selected_skill") != case.get("target_skill"):
            failures.append(f"{case_id}: selected_skill mismatch")
        if routing_evaluation:
            if result.get("case_outcome") != case.get("expected_case_outcome"):
                failures.append(f"{case_id}: case_outcome mismatch")
            if "verdict" in result:
                failures.append(f"{case_id}: routing evaluation forbids verdict")
        else:
            if "expected_verdict" not in case:
                failures.append(f"{case_id}: normal cases require expected_verdict")
            if "expected_case_outcome" in case:
                failures.append(
                    f"{case_id}: normal cases forbid expected_case_outcome"
                )
            if result.get("verdict") != case.get("expected_verdict"):
                failures.append(f"{case_id}: verdict mismatch")
            if "case_outcome" in result:
                failures.append(
                    f"{case_id}: normal results forbid case_outcome"
                )
        if not isinstance(result.get("mutated"), bool):
            failures.append(f"{case_id}: mutated must be boolean")
        elif result.get("mutated") and not case.get("allow_mutation", False):
            failures.append(f"{case_id}: unauthorized mutation reported")
        artifact = result.get("artifact")
        if not isinstance(artifact, dict):
            failures.append(f"{case_id}: artifact must be an object")
        else:
            required_artifact_fields = case["required_artifact_fields"]
            missing_artifacts = sorted(
                set(required_artifact_fields) - set(artifact)
            )
            if missing_artifacts:
                failures.append(f"{case_id}: missing artifact fields {missing_artifacts}")
            blank_artifacts = sorted(
                field
                for field in required_artifact_fields
                if field in artifact and _is_null_or_blank(artifact[field])
            )
            if blank_artifacts:
                failures.append(
                    f"{case_id}: null or blank artifact fields {blank_artifacts}"
                )
            failures.extend(
                _validate_artifact_contracts(
                    case_id,
                    case,
                    result,
                    artifact,
                    (
                        Path(schema_root)
                        if schema_root is not None
                        else DEFAULT_ARTIFACT_SCHEMA_ROOT
                    ),
                )
            )
        labels = result.get("evidence_labels")
        if (
            not isinstance(labels, list)
            or not labels
            or any(label not in EVIDENCE_LABELS for label in labels)
        ):
            failures.append(f"{case_id}: invalid evidence_labels")
        if not any(failure.startswith(f"{case_id}:") for failure in failures):
            passed += 1
    return _failure("PASS" if not failures else "FAIL", len(cases), failures, passed)


def evaluate(
    root: Path | str,
    kind: str,
    results_path: Path | str | None = None,
) -> RunnerEvalSummary:
    root_path = Path(root).resolve()
    cases = load_cases(root_path, kind)
    try:
        results = (
            json.loads(Path(results_path).read_text(encoding="utf-8"))
            if results_path is not None
            else []
        )
    except OSError as error:
        report = _failure(
            "FAIL",
            len(cases),
            [f"runner results could not be read: {error.__class__.__name__}"],
        )
    except json.JSONDecodeError as error:
        report = _failure(
            "FAIL",
            len(cases),
            [
                "runner results file is invalid JSON at "
                f"line {error.lineno} column {error.colno}"
            ],
        )
    else:
        report = None
    if report is None:
        if not isinstance(results, list):
            report = _failure(
                "FAIL", len(cases), ["runner results must be a JSON array"]
            )
        else:
            report = validate_runner_results(
                cases,
                results,
                schema_root=root_path / "evals" / "schema",
            )
    return RunnerEvalSummary(
        verdict=report["verdict"],
        total=report["total"],
        passed=report["passed"],
        failures=list(report["failures"]),
    )


def write_blocked_status(path: Path | str, kind: str, reason: str) -> Path:
    output = Path(path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(
            {
                "_generated": GENERATED_MARKER,
                "verdict": "BLOCKED",
                "kind": kind,
                "reason": reason,
                "observed_cases": 0,
                "passed": 0,
                "pass_rate": None,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return output


def run_cli(kind: str, description: str, argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--export", type=Path)
    parser.add_argument("--results", type=Path)
    parser.add_argument("--status", type=Path)
    args = parser.parse_args(argv)
    if args.export:
        count = export_cases(Path(args.root), kind, args.export)
        print(f"{kind}-export: {count} cases")
    if args.status:
        write_blocked_status(
            args.status,
            kind,
            f"No governed {kind} runner result was supplied",
        )
        print(args.status)
    if args.results:
        summary = evaluate(Path(args.root), kind, args.results)
    elif args.export or args.status:
        return 0
    else:
        summary = evaluate(Path(args.root), kind)
    print(
        json.dumps(
            {
                "verdict": summary.verdict,
                "total": summary.total,
                "passed": summary.passed,
                "failures": summary.failures,
            },
            indent=2,
        )
    )
    if summary.verdict == "PASS":
        return 0
    return 2 if summary.verdict == "BLOCKED" else 1
