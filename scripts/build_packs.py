from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path
from typing import Any

try:
    from scripts.common import load_yaml
except ModuleNotFoundError:
    from common import load_yaml


MARKER = "Generated by scripts/build_packs.py. Do not edit manually."


def _generated_skill(text: str) -> str:
    if text.startswith("---\n"):
        return text.replace("---\n", f"---\n# {MARKER}\n", 1)
    return f"<!-- {MARKER} -->\n{text}"


def _generated_resource(source: Path) -> str:
    text = source.read_text(encoding="utf-8")
    if source.name == "SKILL.md":
        return _generated_skill(text)
    if source.suffix.casefold() in {".py", ".sh", ".ps1", ".yaml", ".yml", ".toml"}:
        return f"# {MARKER}\n\n{text}"
    if source.suffix.casefold() in {".md", ".txt"}:
        return f"<!-- {MARKER} -->\n{text}"
    raise ValueError(f"unsupported skill resource type: {source}")


def _clear_generated_directory(path: Path) -> None:
    if not path.exists():
        return
    for file in (item for item in path.rglob("*") if item.is_file()):
        text = file.read_text(encoding="utf-8", errors="replace")
        if MARKER not in text:
            raise RuntimeError(f"refusing to remove unmanaged pack artifact: {file}")
    shutil.rmtree(path)


def build_pack(root: Path | str, pack: dict[str, Any], output_root: Path | str) -> list[str]:
    root_path = Path(root).resolve()
    output = Path(output_root).resolve() / pack["id"]
    _clear_generated_directory(output)
    output.mkdir(parents=True, exist_ok=True)
    generated_files: list[str] = []
    digest = hashlib.sha256()
    for skill_name in pack["skills"]:
        source_root = root_path / "skills" / skill_name
        for source in sorted(path for path in source_root.rglob("*") if path.is_file()):
            relative_resource = source.relative_to(source_root)
            source_bytes = source.read_bytes()
            digest.update(skill_name.encode("utf-8"))
            digest.update(relative_resource.as_posix().encode("utf-8"))
            digest.update(source_bytes)
            destination = output / "skills" / skill_name / relative_resource
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(_generated_resource(source), encoding="utf-8", newline="\n")
            generated_files.append(destination.relative_to(output).as_posix())
    manifest = {
        "_generated": MARKER,
        "schema_version": 1,
        "pack": pack["id"],
        "description": pack["description"],
        "depends_on": pack["depends_on"],
        "skills": pack["skills"],
        "source_digest": digest.hexdigest(),
    }
    manifest_path = output / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    generated_files.append("manifest.json")
    return sorted(generated_files)


def build_all_packs(root: Path | str, output_root: Path | str) -> dict[str, list[str]]:
    root_path = Path(root).resolve()
    registry = load_yaml(root_path / "registry" / "packs.yaml")
    return {
        pack["id"]: build_pack(root_path, pack, output_root)
        for pack in registry.get("packs", [])
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build deterministic skill packs.")
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--output", default="dist/packs")
    args = parser.parse_args(argv)
    report = build_all_packs(Path(args.root), Path(args.output))
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
